    schema_file.write_text(
        json.dumps({"events": [{"name": "event_id", "type": "STRING"}]})
    )

    result = runner.invoke(
        app,
        [
            "tools",
            "bq-table-change-listener",
            "--project",
            "test-gcp-project",
            "--dataset",
            "telemetry",
            "--path",
            str(tmp_path),
            "--schema-file",
            str(schema_file),
        ],
    )
    assert result.exit_code == 0
    assert "Successfully synchronized 1 view(s)" in result.stdout
    assert (tmp_path / "events.view.lkml").exists()


