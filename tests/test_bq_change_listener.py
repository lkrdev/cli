runner = CliRunner()


def test_is_autogenerated_view():
    assert is_autogenerated_view(f"{AUTOGENERATED_VIEW_HEADER}view: test {{}}") is True
    assert is_autogenerated_view("# AUTOGENERATED BY LKR CLI\nview: test {}") is True
    assert is_autogenerated_view("# Human written LookML view\nview: test {}") is False


def test_generate_lookml_with_new_files_adds_header_only_to_views():
    sdk = MagicMock(spec=ExtendedLooker40SDK)
    sdk.all_project_files.side_effect = [
        [{"id": "existing.view.lkml"}],
        [
            {"id": "existing.view.lkml"},
            {"id": "views/orders.view.lkml"},
            {"id": "my_model.model.lkml"},
        ],
    ]
    sdk.generate_lookml.return_value = ""
    sdk.get_file_content.return_value = "view: orders {\n  sql_table_name: raw.orders ;;\n}\n"

    res = ExtendedLooker40SDK.generate_lookml_with_new_files(
        sdk,
        project_id="my_proj",
        body={"tables": [{"schema": "raw", "table_name": "orders", "base_view": True}]},
        connection="snowflake_conn",
        model_name="my_model",
        folder_name="views",
        file_type_for_explores="model",
        add_autogenerated_header=True,
    )

    assert len(res.new_files) == 2
    sdk.get_file_content.assert_called_once_with(
        project_id="my_proj",
        file_path="views/orders.view.lkml",
        transport_options=None,
    )
    sdk.update_file.assert_called_once()
    call_kwargs = sdk.update_file.call_args.kwargs
    assert call_kwargs["project_id"] == "my_proj"
    file_content: FileContent = call_kwargs["file_content"]
    assert file_content.path == "views/orders.view.lkml"
    assert file_content.content.startswith(AUTOGENERATED_VIEW_HEADER)
    assert "view: orders {" in file_content.content


def test_create_lookml_views_new_and_autogenerated_update():
    sdk = MagicMock()
    # First call: file does not exist -> raises error
    sdk.get_file_content.side_effect = Exception("File not found")

    res = create_lookml_views(
        sdk=sdk,
        project_id="analytics_proj",
        connection="postgres_prod",
        schema="public",
        table="users",
        branch_prefix="custom-prefix/",
    )

    assert res["status"] == "deployed"
    assert res["branch"].startswith("custom-prefix/")
    assert res["synced_views"] == ["views/public/users.view.lkml"]
    sdk.generate_lookml_with_new_files.assert_called_once_with(
        project_id="analytics_proj",
        body={"tables": [{"schema": "public", "table_name": "users", "base_view": True}]},
        connection="postgres_prod",
        model_name="analytics_proj",
        folder_name="views/public",
        file_type_for_explores="none",
        generate_descriptions=True,
        add_autogenerated_header=True,
        allow_update_without_header=False,
    )
    sdk.deploy_to_production.assert_called_once_with(project_id="analytics_proj")
    sdk.update_artifacts.assert_called()


def test_generate_lookml_with_new_files_existing_header_guard():
    import pytest

    sdk = MagicMock(spec=ExtendedLooker40SDK)
    sdk.all_project_files.return_value = [{"id": "views/orders.view.lkml"}]
    sdk.get_file_content.return_value = "# Human view\nview: orders {}\n"

    with pytest.raises(ValueError, match="missing # AUTOGENERATED"):
        ExtendedLooker40SDK.generate_lookml_with_new_files(
            sdk,
            project_id="my_proj",
            body={"tables": [{"schema": "raw", "table_name": "orders", "base_view": True}]},
            connection="snowflake_conn",
            model_name="my_model",
            folder_name="views",
            file_type_for_explores="none",
            add_autogenerated_header=True,
        )

    # Succeeds when allow_update_without_header=True
    sdk.generate_lookml.return_value = ""
    res = ExtendedLooker40SDK.generate_lookml_with_new_files(
        sdk,
        project_id="my_proj",
        body={"tables": [{"schema": "raw", "table_name": "orders", "base_view": True}]},
        connection="snowflake_conn",
        model_name="my_model",
        folder_name="views",
        file_type_for_explores="none",
        add_autogenerated_header=True,
        allow_update_without_header=True,
    )
    assert len(res.new_files) == 1
    sdk.delete_file.assert_called_once_with(
        project_id="my_proj",
        file_path="views/orders.view.lkml",
        transport_options=None,
    )


def test_bigquery_audit_metadata_and_pubsub_event():
    import base64

    from lkr.tools.lookml import BigQueryAuditEvent

    audit_log = {
        "protoPayload": {
            "@type": "type.googleapis.com/google.cloud.audit.AuditLog",
            "methodName": "google.cloud.bigquery.v2.TableService.PatchTable",
            "metadata": {
                "@type": "type.googleapis.com/google.cloud.audit.BigQueryAuditMetadata",
                "tableChange": {
                    "table": {
                        "tableName": "projects/corp-bq/datasets/finance/tables/ledger",
                        "schemaJson": '{"fields":[{"name":"id","type":"STRING"}]}',
                    },
                    "reason": "TABLE_UPDATE_REQUEST",
                },
            },
        }
    }
    encoded = base64.b64encode(json.dumps(audit_log).encode("utf-8")).decode("utf-8")
    ev = BigQueryAuditEvent.model_validate({"message": {"data": encoded}})
    assert ev.resolve_target() == (
        "corp-bq",
        "finance",
        "ledger",
        "google.cloud.bigquery.v2.TableService.PatchTable",
    )


def test_create_lookml_views_aborts_on_missing_header():
    sdk = MagicMock()
    sdk.get_file_content.return_value = "# Custom human view\nview: orders {\n  dimension: id {}\n}\n"

    res = create_lookml_views(
        sdk=sdk,
        project_id="analytics_proj",
        connection="bq_conn",
        dataset="my_gcp_proj",
        schema="raw",
        table="orders",
    )

    assert res["status"] == "error_missing_header"
    assert res["synced_views"] == []
    assert len(res["errors"]) == 1
    assert "missing # AUTOGENERATED header" in res["errors"][0]["error"]
    sdk.generate_lookml_with_new_files.assert_not_called()
    sdk.delete_file.assert_not_called()
    sdk.update_artifacts.assert_called_once()


def test_create_lookml_views_wildcard_match():
    sdk = MagicMock()
    sdk.connection_schemas.return_value = [{"name": "raw"}, {"name": "staging"}]
    sdk.connection_tables.return_value = [
        {"tables": [{"name": "orders_2025"}, {"name": "orders_2026"}, {"name": "customers"}]}
    ]
    sdk.get_file_content.side_effect = Exception("Not found")

    res = create_lookml_views(
        sdk=sdk,
        project_id="ecomm",
        connection="snowflake_db",
        match="raw.orders_*",
    )

    assert res["status"] == "deployed"
    assert res["synced_views"] == [
        "views/raw/orders_2025.view.lkml",
        "views/raw/orders_2026.view.lkml",
    ]
    assert sdk.generate_lookml_with_new_files.call_count == 2


def test_create_lookml_views_deploy_fallback_to_github_pr(monkeypatch):
    monkeypatch.setenv("GITHUB_TOKEN", "ghp_test_token")
    sdk = MagicMock()
    sdk.get_file_content.return_value = f"{AUTOGENERATED_VIEW_HEADER}view: events {{}}"
    sdk.deploy_to_production.side_effect = Exception("Pull request required")
    sdk.project.return_value = {
        "git_remote_url": "https://github.com/acme/lookml-repo.git",
        "git_production_branch_name": "main",
    }

    mock_resp = MagicMock()
    mock_resp.ok = True
    mock_resp.json.return_value = {"html_url": "https://github.com/acme/lookml-repo/pull/42"}

    with patch("lkr.tools.lookml.requests.post", return_value=mock_resp) as mock_post:
        res = create_lookml_views(
            sdk=sdk,
            project_id="ecomm",
            connection="bq_conn",
            schema="telemetry",
            table="events",
            branch_prefix="auto-view/",
        )

    assert res["status"] == "pr_opened"
    assert res["pr_url"] == "https://github.com/acme/lookml-repo/pull/42"
    assert res["branch"].startswith("auto-view/")
    sdk.delete_file.assert_called_once_with(
        project_id="ecomm", file_path="views/telemetry/events.view.lkml"
    )
    mock_post.assert_called_once()


def test_cli_lookml_create_with_event_json():
    sdk = MagicMock()
    sdk.get_file_content.side_effect = Exception("Not found")
    mock_auth = MagicMock()
    mock_auth.get_current_sdk.return_value = sdk

    event_payload = json.dumps(
        {
            "protoPayload": {
                "methodName": "google.cloud.bigquery.v2.TableService.UpdateTable",
                "resourceName": "projects/my-gcp/datasets/analytics/tables/sessions",
            }
        }
    )

    with patch("lkr.tools.lookml.get_auth", return_value=mock_auth):
        result = runner.invoke(
            app,
            [
                "tools",
                "lookml",
                "create",
                "--project-id",
                "my_looker_proj",
                "--connection",
                "my_db_conn",
                "--branch-prefix",
                "sync-branch/",
                "--event-json",
                event_payload,
            ],
        )

    assert result.exit_code == 0
    assert "Successfully created/updated 1 view(s)" in result.stdout
    assert "views/my-gcp/analytics/sessions.view.lkml" in result.stdout
