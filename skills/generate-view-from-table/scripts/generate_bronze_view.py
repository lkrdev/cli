"""Generate 1:1 Bronze LookML view file(s) on the active Looker dev branch without creating explores."""


def main():
    try:
        folder = str(folder_name) or "bronze"  # ty: ignore[unresolved-reference]
    except NameError:
        folder = "bronze"
    tables = [
        {"schema": schema_name, "table_name": t.strip(), "base_view": True}  # ty: ignore[unresolved-reference]
        for t in table_name.split(",")  # ty: ignore[unresolved-reference]
        if t.strip()
    ]
    res = (
        generate_lookml_with_new_files(  # ty: ignore[unresolved-reference]
            project_id=project_id,  # ty: ignore[unresolved-reference]
            body={"tables": tables},
            connection=connection_name,  # ty: ignore[unresolved-reference]
            model_name=model_name,  # ty: ignore[unresolved-reference]
            folder_name=folder,
            file_type_for_explores="none",
            generate_descriptions=True,
            add_autogenerated_header=True,
        )
        or {}
    )
    return {
        "new_files": [f.get("id") or f.get("path") for f in (res.get("new_files") or [])],
    }


main()
