"""Reset developer workspace to production, create a timestamped branch, and pre-generate missing Bronze views."""

import json
import re


def main():
    user = me()  # ty: ignore[unresolved-reference]
    run_id = f"{ts_utc}_{user['id']}"  # ty: ignore[unresolved-reference]
    proj = project(project_id=project_id) or {}  # ty: ignore[unresolved-reference]

    try:
        reset_project_to_production(project_id=project_id)  # ty: ignore[unresolved-reference]
    except Exception:
        create_developer_copy(project_id=project_id)  # ty: ignore[unresolved-reference]
        reset_project_to_production(project_id=project_id)  # ty: ignore[unresolved-reference]

    prod_name = proj.get("git_production_branch_name") or "main"
    try:
        prod_branch = find_git_branch(project_id=project_id, branch_name=prod_name) or {}  # ty: ignore[unresolved-reference]
    except Exception:
        prod_branch = {}

    target_ref = (
        prod_branch.get("remote_ref")
        or prod_branch.get("ref")
        or (git_branch(project_id=project_id) or {}).get("ref")  # ty: ignore[unresolved-reference]
    )
    body = {"name": run_id, "ref": target_ref} if target_ref else {"name": run_id}
    create_git_branch(project_id=project_id, body=body)  # ty: ignore[unresolved-reference]

    out = {
        "run_id": run_id,
        "user_id": str(user["id"]),
        "project_id": project_id,  # ty: ignore[unresolved-reference]
        "production_branch": prod_name,
        "production_ref": target_ref,
        "branch_name": run_id,
        "git_remote_url": proj.get("git_remote_url") or "",
    }

    try:
        raw_parsed = parsed_sql_json  # ty: ignore[unresolved-reference]
    except NameError:
        raw_parsed = None
    if not raw_parsed:
        return out

    try:
        parsed = json.loads(raw_parsed) if isinstance(raw_parsed, str) else (raw_parsed or {})
    except Exception:
        parsed = {}
    wanted = {}
    for q in (parsed.get("queries") if isinstance(parsed, dict) else None) or []:
        ctes = {str(c.get("name") or "").lower() for c in (q.get("ctes") or []) if isinstance(c, dict)}
        for t in q.get("tables") or []:
            if isinstance(t, dict):
                tbl = str(t.get("name") or "").strip()
                cat, db = str(t.get("catalog") or "").strip(), str(t.get("db") or "").strip()
                sch = f"{cat}.{db}" if (cat and db) else db
                if tbl and sch and "*" not in tbl and tbl.lower() not in ctes:
                    wanted[(sch, tbl)] = None
    if not wanted:
        return out

    files = all_project_files(project_id=project_id) or []  # ty: ignore[unresolved-reference]
    paths = [str(f.get("path") or f.get("id") or "").lstrip("/") for f in files if isinstance(f, dict)]
    existing_bronze = {
        p.rsplit("/", 1)[-1][:-10].lower() for p in paths if p.startswith("bronze/") and p.endswith(".view.lkml")
    }
    missing = [{"schema": s, "table_name": t, "base_view": True} for s, t in wanted if t.lower() not in existing_bronze]
    model_files = [p for p in paths if p.endswith(".model.lkml") and "/" not in p]
    if not missing or not model_files:
        return out

    try:
        mc = get_file_content(project_id=project_id, file_path=model_files[0]) or ""  # ty: ignore[unresolved-reference]
    except Exception:
        mc = ""
    cm = re.search(r'^\s*connection:\s*["\']?([^"\'\s;#]+)["\']?', mc, re.MULTILINE)
    if cm:
        if not any(p.startswith("bronze/") for p in paths):
            try:
                create_project_directory(project_id=project_id, directory_path="bronze")  # ty: ignore[unresolved-reference]
            except Exception:
                pass
        res = (
            generate_lookml_with_new_files(  # ty: ignore[unresolved-reference]
                project_id=project_id,  # ty: ignore[unresolved-reference]
                body={"tables": missing},
                connection=cm.group(1).strip(),
                model_name=model_files[0][:-11],
                folder_name="bronze",
                file_type_for_explores="none",
                generate_descriptions=True,
                add_autogenerated_header=True,
            )
            or {}
        )
        out["generated_bronze_files"] = [
            str(f.get("path") or f.get("id")).lstrip("/")
            for f in (res.get("new_files") or [])
            if isinstance(f, dict) and (f.get("path") or f.get("id"))
        ]
    return out


main()
