    def generate_lookml(
        self,
        project_id: str,
        body: ProjectGenerationRequest | dict[str, object],
        connection: str,
        model_name: str,
        folder_name: str,
        file_type_for_explores: str,
        generate_descriptions: bool | None = None,
        generate_helper_text: bool | None = None,
        prefixes: str | None = None,
        transport_options: transport.TransportOptions | None = None,
    ) -> str:
        """Generate LookML in a project.

        Args:
            project_id: Id of project.
            body: Generation parameters.
            connection: Name of connection.
            model_name: Name of model or Explore file to generate.
            folder_name: Path of the folder to place generated files.
            file_type_for_explores: What type of file to place Explores in, if any. Valid values are model, explore, none. Defaults to model.
            generate_descriptions: Generate descriptions for columns that have them in BigQuery. Defaults to True.
            generate_helper_text: Generate helper text for LookML.
            prefixes: Case sensitive table prefixes to be ignored when naming view files.
            transport_options: Optional transport options.

        Returns:
            str: Empty string on successful LookML generation.
        """
        project_id = self.encode_path_param(project_id)
        path = f"/projects/{project_id}/generate"
        request_body = self._prepare_body(body)
        return cast(
            str,
            self.post(
                path=path,
                structure=str,
                query_params=self._qp(
                    connection=connection,
                    model_name=model_name,
                    folder_name=folder_name,
                    file_type_for_explores=file_type_for_explores,
                    generate_descriptions=generate_descriptions,
                    generate_helper_text=generate_helper_text,
                    prefixes=prefixes,
                ),
                body=request_body,
                transport_options=transport_options,
            ),
        )

    def generate_lookml_with_new_files(
        self,
        project_id: str,
        body: ProjectGenerationRequest | dict[str, object],
        connection: str,
        model_name: str,
        folder_name: str,
        file_type_for_explores: str,
        generate_descriptions: bool | None = None,
        generate_helper_text: bool | None = None,
        prefixes: str | None = None,
        add_autogenerated_header: bool = False,
        allow_update_without_header: bool = False,
        transport_options: transport.TransportOptions | None = None,
    ) -> GenerateLookMLWithNewFilesResponse:
        """Generate LookML in a project and return the API response along with newly created files.

        Args:
            project_id: Id of project.
            body: Generation parameters.
            connection: Name of connection.
            model_name: Name of model or Explore file to generate.
            folder_name: Path of the folder to place generated files.
            file_type_for_explores: What type of file to place Explores in, if any. Valid values are model, explore, none. Defaults to model.
            generate_descriptions: Generate descriptions for columns that have them in BigQuery. Defaults to True.
            generate_helper_text: Generate helper text for LookML.
            prefixes: Case sensitive table prefixes to be ignored when naming view files.
            add_autogenerated_header: Prepend the standardized # AUTOGENERATED header to newly created .view.lkml files.
            allow_update_without_header: Allow overwriting existing .view.lkml files even if they lack the # AUTOGENERATED header.
            transport_options: Optional transport options.

        Returns:
            GenerateLookMLWithNewFilesResponse: The API response from generate_lookml along with a list of newly created files.
        """
        def _get_file_id(f: object) -> str:
            if isinstance(f, dict):
                return str(f.get("id") or f.get("path") or str(f))
            fid = getattr(f, "id", None)
            if fid is not None:
                return str(fid)
            fpath = getattr(f, "path", None)
            if fpath is not None:
                return str(fpath)
            return str(f)

        files_before = (
            self.all_project_files(
                project_id=project_id,
                transport_options=transport_options,
            )
            or []
        )
        before_ids = {_get_file_id(f) for f in files_before}

        raw_tables = cast(
            Sequence[object],
            (
                body.get("tables")
                if isinstance(body, dict)
                else getattr(body, "tables", None)
            )
            or [],
        )
        clean_folder = (folder_name or "").strip("/")
        regenerated_paths: list[str] = []
        for t in raw_tables:
            t_name = (
                (t.get("view_name") or t.get("table_name"))
                if isinstance(t, dict)
                else (getattr(t, "view_name", None) or getattr(t, "table_name", None))
            )
            if not t_name:
                continue
            view_path = (
                f"{clean_folder}/{t_name}.view.lkml"
                if clean_folder
                else f"{t_name}.view.lkml"
            )
            if view_path not in before_ids:
                continue
            existing = (
                self.get_file_content(
                    project_id=project_id,
                    file_path=view_path,
                    transport_options=transport_options,
                )
                or ""
            )
            if not allow_update_without_header and not existing.lstrip().startswith(
                "# AUTOGENERATED"
            ):
                raise ValueError(
                    f"Refusing to overwrite {view_path}: missing # AUTOGENERATED "
                    "header comment at top of file."
                )
            try:
                self.delete_file(
                    project_id=project_id,
                    file_path=view_path,
                    transport_options=transport_options,
                )
            except Exception:  # noqa: BLE001, S110
                pass
            before_ids.discard(view_path)
            regenerated_paths.append(view_path)

        response = self.generate_lookml(
            project_id=project_id,
            body=body,
            connection=connection,
            model_name=model_name,
            folder_name=folder_name,
            file_type_for_explores=file_type_for_explores,
            generate_descriptions=generate_descriptions,
            generate_helper_text=generate_helper_text,
            prefixes=prefixes,
            transport_options=transport_options,
        )

        files_after = (
            self.all_project_files(
                project_id=project_id,
                transport_options=transport_options,
            )
            or []
        )

        new_files = [f for f in files_after if _get_file_id(f) not in before_ids]
        seen_new = {_get_file_id(f) for f in new_files}
        for rp in regenerated_paths:
            if rp not in seen_new:
                new_files.append({"id": rp, "path": rp})

        if add_autogenerated_header:
            for f in new_files:
                file_path = _get_file_id(f)
                if file_path.endswith(".view.lkml"):
                    content = (
                        self.get_file_content(
                            project_id=project_id,
                            file_path=file_path,
                            transport_options=transport_options,
                        )
                        or ""
                    )
                    if not content.lstrip().startswith("# AUTOGENERATED"):
                        self.update_file(
                            project_id=project_id,
                            file_content=FileContent(
                                path=file_path,
                                content=f"{AUTOGENERATED_VIEW_HEADER}{content}",
                            ),
                            transport_options=transport_options,
                        )

        return GenerateLookMLWithNewFilesResponse(
            generate_lookml=response, new_files=new_files
        )

