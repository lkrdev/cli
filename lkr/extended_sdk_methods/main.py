    def execute_looker_query(
        self,
        spec: dict[str, object] | list[dict[str, object]],
        transport_options: transport.TransportOptions | None = None,
    ) -> list[dict[str, object]]:
        """Execute one or more Looker queries with SQL CTE joins and SQL Runner / Python fallback.

        1. Single query: delegates to run_inline_query('json', body). Zero queries raises ValueError.
        2. Multi-query (source_queries > 1): fetches SQL via run_inline_query('sql', ...),
           strips trailing LIMIT on -1 limits, warns and ignores source-query table calculations,
           and builds a CTE JOIN SQL query from merge_fields and join_type.
        3. Without final-select table calculations: creates and runs a SQL Runner query and returns JSON rows.
        4. With final-select table calculations: creates and initializes a SQL Runner query, then executes
           a sql__{slug} / sql_runner_query Explore query to evaluate table calculations.
        5. Corner cases: falls back to Python client-side join (with warnings for row limits and unprocessed
           table calculations) if the user lacks SQL Runner permissions or SQL Runner execution fails.
        """
        _bind_kda_sdk(self, transport_options)
        return _execute_looker_query(
            spec=cast(
                dict[str, object] | list[dict[str, object]],
                ExtendedLooker40SDK._prepare_body(self, spec),
            )
            if not isinstance(spec, list)
            else spec,
            transport_options=transport_options,
        )

