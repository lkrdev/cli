class ExtendedLooker40SDK(Looker40SDK):
    def _prepare_body(self, body: object) -> api_methods.TBody:
        if body is None:
            return None
        if hasattr(body, "model_dump") and callable(body.model_dump):
            return cast(api_methods.TBody, body.model_dump())
        if hasattr(body, "dict") and callable(body.dict):
            return cast(api_methods.TBody, body.dict())
        if hasattr(body, "__dict__") and not isinstance(body, (dict, list, str, bytes)):
            return cast(api_methods.TBody, vars(body))
        return cast(api_methods.TBody, body)

    def delete(
        self,
        path: str,
        structure: api_methods.TStructure = None,
        query_params: api_methods.TQueryParams | None = None,
        transport_options: transport.TransportOptions | None = None,
    ) -> api_methods.TReturn:
        """DELETE method corrected to include query_params."""
        params = self._convert_query_params(query_params) if query_params else None
        response = self.transport.request(
            transport.HttpMethod.DELETE,
            self._path(path),
            query_params=params,
            body=None,
            authenticator=self.auth.authenticate,
            transport_options=transport_options,
        )
        return self._return(response, structure)

    def _qp(self, **params: object) -> api_methods.TQueryParams:
        return cast(
            api_methods.TQueryParams,
            self._convert_query_params(cast(api_methods.TQueryParams, params)),
        )

