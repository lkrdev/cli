#[wasm_bindgen(js_name = search)]
pub fn js_search(pattern: String) -> String {
    let results = search_with_lookups(&pattern);
    if results.is_empty() {
        format!("No matches found for '{pattern}'.")
    } else {
        let sep = format!("\n\n{}\n\n", "-".repeat(40));
        results
            .into_iter()
            .map(|r| r.trim().to_string())
            .collect::<Vec<_>>()
            .join(&sep)
    }
}

