pub trait SdkTransport {
    fn invoke<'a>(
        &'a self,
        http_method: &'a str,
        path: &'a str,
        params: Option<Value>,
        body: Option<Value>,
        options: Option<Value>,
    ) -> Pin<Box<dyn Future<Output = Result<Value, String>> + 'a>>;

    fn host_data(&self) -> Value {
        Value::Object(Map::new())
    }
}

fn bind_operation_args(
    op: &OperationMeta,
    pos_args: &[Value],
    kw_args: &Map<String, Value>,
) -> Result<Map<String, Value>, String> {
    let mut bound = Map::new();
    for (idx, val) in pos_args.iter().enumerate() {
        if let Some(pmeta) = op.params.get(idx) {
            bound.insert(pmeta.name.clone(), val.clone());
        } else {
            return Err(format!(
                "{}() takes at most {} positional arguments ({} given)",
                op.name,
                op.params.len(),
                pos_args.len()
            ));
        }
    }
    for (k, v) in kw_args {
        bound.insert(k.clone(), v.clone());
    }
    for pmeta in &op.params {
        if pmeta.required && !bound.contains_key(&pmeta.name) {
            return Err(format!(
                "{}() missing required argument: '{}'",
                op.name, pmeta.name
            ));
        }
    }
    Ok(bound)
}

fn clean_query_params(raw: &Map<String, Value>) -> Option<Value> {
    let mut cleaned = Map::new();
    for (k, v) in raw {
        if !v.is_null() {
            cleaned.insert(k.clone(), v.clone());
        }
    }
    if cleaned.is_empty() {
        None
    } else {
        Some(Value::Object(cleaned))
    }
}

fn get_file_id(f: &Value) -> String {
    if let Some(obj) = f.as_object() {
        if let Some(id) = obj.get("id").and_then(|v| v.as_str()) {
            return id.to_string();
        }
        if let Some(p) = obj.get("path").and_then(|v| v.as_str()) {
            return p.to_string();
        }
    }
    match f {
        Value::String(s) => s.clone(),
        other => other.to_string(),
    }
}

async fn execute_generate_lookml_with_new_files<T: SdkTransport>(
    transport: &T,
    bound: &Map<String, Value>,
) -> Result<Value, String> {
    let project_id_val = bound
        .get("project_id")
        .ok_or_else(|| "missing project_id".to_string())?;
    let encoded_pid = encode_path_param(project_id_val);
    let options = bound
        .get("transport_options")
        .cloned()
        .filter(|v| !v.is_null());
    let body = bound.get("body").cloned().unwrap_or(Value::Null);
    let folder_name = bound
        .get("folder_name")
        .and_then(|v| v.as_str())
        .unwrap_or("");
    let add_header = bound
        .get("add_autogenerated_header")
        .and_then(|v| v.as_bool())
        .unwrap_or(false);
    let allow_overwrite = bound
        .get("allow_update_without_header")
        .and_then(|v| v.as_bool())
        .unwrap_or(false);

    let files_path = format!("/projects/{encoded_pid}/files");
    let files_before_val = transport
        .invoke("GET", &files_path, None, None, options.clone())
        .await?;
    let mut before_ids: HashSet<String> = files_before_val
        .as_array()
        .map(|arr| arr.iter().map(get_file_id).collect())
        .unwrap_or_default();

    let clean_folder = folder_name.trim_matches('/');
    let mut regenerated_paths: Vec<String> = Vec::new();

    if let Some(tables) = body.get("tables").and_then(|v| v.as_array()) {
        for t in tables {
            let t_name = t
                .get("view_name")
                .and_then(|v| v.as_str())
                .or_else(|| t.get("table_name").and_then(|v| v.as_str()))
                .unwrap_or("");
            if t_name.is_empty() {
                continue;
            }
            let view_path = if clean_folder.is_empty() {
                format!("{t_name}.view.lkml")
            } else {
                format!("{clean_folder}/{t_name}.view.lkml")
            };
            if !before_ids.contains(&view_path) {
                continue;
            }
            let content_path = format!("/projects/{encoded_pid}/file/content");
            let existing_val = transport
                .invoke(
                    "GET",
                    &content_path,
                    Some(json!({ "file_path": view_path })),
                    None,
                    options.clone(),
                )
                .await?;
            let existing = existing_val.as_str().unwrap_or("");
            if !allow_overwrite && !existing.trim_start().starts_with("# AUTOGENERATED") {
                return Err(format!(
                    "Refusing to overwrite {view_path}: missing # AUTOGENERATED header comment at top of file."
                ));
            }
            let _ = transport
                .invoke(
                    "DELETE",
                    &files_path,
                    Some(json!({ "file_path": view_path })),
                    None,
                    options.clone(),
                )
                .await;
            before_ids.remove(&view_path);
            regenerated_paths.push(view_path);
        }
    }

    let mut qmap = Map::new();
    for qk in [
        "connection",
        "model_name",
        "folder_name",
        "file_type_for_explores",
        "generate_descriptions",
        "generate_helper_text",
        "prefixes",
    ] {
        if let Some(v) = bound.get(qk) {
            if !v.is_null() {
                qmap.insert(qk.to_string(), v.clone());
            }
        }
    }
    let gen_path = format!("/projects/{encoded_pid}/generate");
    let gen_resp = transport
        .invoke(
            "POST",
            &gen_path,
            clean_query_params(&qmap),
            Some(body),
            options.clone(),
        )
        .await?;

    let files_after_val = transport
        .invoke("GET", &files_path, None, None, options.clone())
        .await?;
    let mut new_files: Vec<Value> = files_after_val
        .as_array()
        .map(|arr| {
            arr.iter()
                .filter(|f| !before_ids.contains(&get_file_id(f)))
                .cloned()
                .collect()
        })
        .unwrap_or_default();

    let seen_new: HashSet<String> = new_files.iter().map(get_file_id).collect();
    for rp in regenerated_paths {
        if !seen_new.contains(&rp) {
            new_files.push(json!({ "id": rp, "path": rp }));
        }
    }

    if add_header {
        let content_path = format!("/projects/{encoded_pid}/file/content");
        for f in &new_files {
            let file_path = get_file_id(f);
            if file_path.ends_with(".view.lkml") {
                let cval = transport
                    .invoke(
                        "GET",
                        &content_path,
                        Some(json!({ "file_path": file_path })),
                        None,
                        options.clone(),
                    )
                    .await?;
                let content = cval.as_str().unwrap_or("");
                if !content.trim_start().starts_with("# AUTOGENERATED") {
                    let _ = transport
                        .invoke(
                            "PUT",
                            &files_path,
                            None,
                            Some(json!({
                                "path": file_path,
                                "content": format!("{AUTOGENERATED_VIEW_HEADER}{content}")
                            })),
                            options.clone(),
                        )
                        .await?;
                }
            }
        }
    }

    Ok(json!({
        "generate_lookml": match gen_resp {
            Value::Null => Value::String(String::new()),
            other => other,
        },
        "new_files": new_files
    }))
}

async fn execute_sdk_operation<T: SdkTransport>(
    transport: &T,
    op: &OperationMeta,
    pos_args: &[Value],
    kw_args: &Map<String, Value>,
) -> Result<Value, String> {
    let bound = bind_operation_args(op, pos_args, kw_args)?;

    if op.name == "generate_lookml_with_new_files" {
        return execute_generate_lookml_with_new_files(transport, &bound).await;
    }

    let options = bound
        .get("transport_options")
        .cloned()
        .filter(|v| !v.is_null());

    if let Some(raw_verb) = op.http_method.strip_prefix("RAW_") {
        let raw_path = bound
            .get("path")
            .and_then(|v| v.as_str())
            .ok_or_else(|| format!("{}() missing 'path' string argument", op.name))?;
        let query_params = bound
            .get("query_params")
            .and_then(|v| v.as_object())
            .and_then(clean_query_params);
        let body = bound.get("body").cloned().filter(|v| !v.is_null());
        return transport
            .invoke(raw_verb, raw_path, query_params, body, options)
            .await;
    }

    let mut path = op.path.clone();
    let mut query_map = Map::new();
    let mut body: Option<Value> = None;

    for pmeta in &op.params {
        let Some(val) = bound.get(&pmeta.name) else {
            continue;
        };
        if val.is_null() {
            continue;
        }
        match pmeta.location.as_str() {
            "path" => {
                let placeholder = format!("{{{}}}", pmeta.name);
                path = path.replace(&placeholder, &encode_path_param(val));
            }
            "query" => {
                query_map.insert(pmeta.name.clone(), val.clone());
            }
            "body" => {
                body = Some(val.clone());
            }
            _ => {}
        }
    }

    // Special handling for custom ExtendedLooker40SDK wrappers
    match op.name.as_str() {
        "create_project_directory" => {
            if let Some(dir_path) = bound.get("directory_path") {
                body = Some(json!({ "path": dir_path }));
            }
        }
        "delete_project_directory" => {
            if let Some(dir_path) = bound.get("directory_path") {
                query_map.insert("path".to_string(), dir_path.clone());
            }
        }
        "publish_agent" => {
            if body.is_none() {
                body = Some(json!({}));
            }
        }
        "update_published_agent" | "unpublish_agent" => {
            body = Some(json!({}));
        }
        _ => {}
    }

    let query_params = clean_query_params(&query_map);
    transport
        .invoke(&op.http_method, &path, query_params, body, options)
        .await
}

