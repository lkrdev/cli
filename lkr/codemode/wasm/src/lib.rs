fn compile_wildcard_regex(query: &str) -> Regex {
    let escaped = regex::escape(query)
        .replace(r"\*", ".*")
        .replace(r"\?", ".");
    RegexBuilder::new(&escaped)
        .case_insensitive(true)
        .build()
        .unwrap_or_else(|_| {
            RegexBuilder::new(&regex::escape(query))
                .case_insensitive(true)
                .build()
                .expect("escaped regex must compile")
        })
}

struct FuncMatch {
    name: String,
    hit_in_name: bool,
    matching_lines: Vec<String>,
    hit_in_params: bool,
    output_fields: Vec<String>,
}

struct TypeMatch {
    name: String,
    hit_in_name: bool,
    matching_props: Vec<String>,
    matching_desc: Vec<String>,
}

fn get_func_matches(query: &str) -> Vec<FuncMatch> {
    let pattern = compile_wildcard_regex(query);
    let meta = metadata();
    let mut matches = Vec::new();

    for (name, op) in &meta.operations {
        let hit_in_name = pattern.is_match(name);
        let mut matching_lines = Vec::new();
        if !op.doc.is_empty() {
            for line in op.doc.lines() {
                if pattern.is_match(line) {
                    matching_lines.push(line.trim().to_string());
                }
            }
        }
        let hit_in_params = op.params.iter().any(|p| pattern.is_match(&p.name));
        let output_fields: Vec<String> = op
            .output_fields
            .iter()
            .filter(|f| pattern.is_match(&f.name))
            .map(|f| f.name.clone())
            .collect();
        let hit_in_output = !output_fields.is_empty();

        if hit_in_name || !matching_lines.is_empty() || hit_in_params || hit_in_output {
            matches.push(FuncMatch {
                name: name.clone(),
                hit_in_name,
                matching_lines,
                hit_in_params,
                output_fields,
            });
        }
    }
    matches
}

fn get_type_matches(query: &str) -> Vec<TypeMatch> {
    let pattern = compile_wildcard_regex(query);
    let meta = metadata();
    let mut matches = Vec::new();

    for (type_name, props) in &meta.definitions {
        let hit_in_name = pattern.is_match(type_name);
        let mut matching_props = Vec::new();
        let mut matching_desc = Vec::new();

        for (prop_name, prop_val) in props {
            if pattern.is_match(prop_name) {
                matching_props.push(prop_name.clone());
            }
            if !prop_val.description.is_empty() && pattern.is_match(&prop_val.description) {
                let first_line = prop_val.description.trim().lines().next().unwrap_or("");
                matching_desc.push(format!("{prop_name}: {first_line}"));
            }
        }

        if hit_in_name || !matching_props.is_empty() || !matching_desc.is_empty() {
            matches.push(TypeMatch {
                name: type_name.clone(),
                hit_in_name,
                matching_props,
                matching_desc,
            });
        }
    }
    matches
}

pub fn search_help(query: &str) -> String {
    let func_matches = get_func_matches(query);
    let type_matches = get_type_matches(query);

    if func_matches.is_empty() && type_matches.is_empty() {
        return format!("No matches found for '{query}'.");
    }

    let mut lines = Vec::new();
    for m in func_matches {
        let mut hit_info = Vec::new();
        if m.hit_in_name {
            hit_info.push("Name match".to_string());
        }
        if let Some(first_doc) = m.matching_lines.first() {
            hit_info.push(format!("Doc hit: \"{first_doc}\""));
        }
        if m.hit_in_params {
            hit_info.push("Input param match".to_string());
        }
        if !m.output_fields.is_empty() {
            let preview: Vec<&str> = m.output_fields.iter().take(2).map(String::as_str).collect();
            hit_info.push(format!("Output field match: {}", preview.join(", ")));
        }
        lines.push(format!("- Function: {} ({})", m.name, hit_info.join(" | ")));
    }

    for m in type_matches {
        let mut hit_info = Vec::new();
        if m.hit_in_name {
            hit_info.push("Name match".to_string());
        }
        if !m.matching_props.is_empty() {
            let preview: Vec<&str> = m
                .matching_props
                .iter()
                .take(2)
                .map(String::as_str)
                .collect();
            hit_info.push(format!("Property match: {}", preview.join(", ")));
        }
        if let Some(first_desc) = m.matching_desc.first() {
            hit_info.push(format!("Comment hit: \"{first_desc}\""));
        }
        lines.push(format!("- Type: {} ({})", m.name, hit_info.join(" | ")));
    }

    format!("Matches found for '{query}':\n{}", lines.join("\n"))
}

pub fn lookup_type(type_name: &str) -> String {
    let meta = metadata();
    let resolved_name = if meta.definitions.contains_key(type_name) {
        type_name.to_string()
    } else if let Some(found) = meta
        .definitions
        .keys()
        .find(|k| k.eq_ignore_ascii_case(type_name))
    {
        found.clone()
    } else {
        return format!("Type '{type_name}' not found.");
    };

    let mut seen_types = HashSet::new();
    let mut result_lines = Vec::new();

    fn resolve_type(
        name: &str,
        defs: &BTreeMap<String, BTreeMap<String, PropMeta>>,
        seen: &mut HashSet<String>,
        lines: &mut Vec<String>,
    ) {
        if !seen.insert(name.to_string()) {
            return;
        }
        let Some(props) = defs.get(name) else { return };
        lines.push(format!("Type: {name}"));
        if props.is_empty() {
            lines.push("  (No properties)".to_string());
            return;
        }

        for (prop_name, prop_val) in props {
            if !prop_val.ref_path.is_empty() {
                let ref_type = prop_val.ref_path.rsplit('/').next().unwrap_or("");
                lines.push(format!("  - {prop_name}: {ref_type} (Ref)"));
            } else if prop_val.prop_type == "array" {
                if let Some(items) = &prop_val.items {
                    if !items.ref_path.is_empty() {
                        let ref_type = items.ref_path.rsplit('/').next().unwrap_or("");
                        lines.push(format!("  - {prop_name}: Array of {ref_type}"));
                    } else {
                        lines.push(format!("  - {prop_name}: Array of {}", items.prop_type));
                    }
                } else {
                    lines.push(format!("  - {prop_name}: Array of "));
                }
            } else {
                lines.push(format!("  - {prop_name}: {}", prop_val.prop_type));
            }

            if !prop_val.description.is_empty() {
                for dl in prop_val.description.trim().lines() {
                    lines.push(format!("      # {dl}"));
                }
            }
        }

        for prop_val in props.values() {
            if !prop_val.ref_path.is_empty() {
                let ref_type = prop_val.ref_path.rsplit('/').next().unwrap_or("");
                if defs.contains_key(ref_type) && !seen.contains(ref_type) {
                    lines.push(String::new());
                    resolve_type(ref_type, defs, seen, lines);
                }
            }
            if prop_val.prop_type == "array" {
                if let Some(items) = &prop_val.items {
                    if !items.ref_path.is_empty() {
                        let ref_type = items.ref_path.rsplit('/').next().unwrap_or("");
                        if defs.contains_key(ref_type) && !seen.contains(ref_type) {
                            lines.push(String::new());
                            resolve_type(ref_type, defs, seen, lines);
                        }
                    }
                }
            }
        }
    }

    resolve_type(
        &resolved_name,
        &meta.definitions,
        &mut seen_types,
        &mut result_lines,
    );
    result_lines.join("\n")
}

pub fn lookup_function(name: &str) -> String {
    let meta = metadata();
    if let Some(op) = meta.operations.get(name) {
        let doc = if op.doc.is_empty() {
            "No docstring available."
        } else {
            op.doc.as_str()
        };
        let inputs_str = if op.params.is_empty() {
            "None".to_string()
        } else {
            op.params
                .iter()
                .map(|p| format!("- {}: {}", p.name, p.type_str))
                .collect::<Vec<_>>()
                .join("\n")
        };
        let mut outputs_str = format!("Return Type: {}", op.return_type);
        if !op.output_fields.is_empty() {
            let fields_str = op
                .output_fields
                .iter()
                .map(|f| format!("  - {}: {}", f.name, f.type_str))
                .collect::<Vec<_>>()
                .join("\n");
            outputs_str.push_str("\nFields:\n");
            outputs_str.push_str(&fields_str);
        }
        return format!(
            "\nFunction: {name}\n\nDocstring:\n{doc}\n\nInputs:\n{inputs_str}\n\nOutputs:\n{outputs_str}\n"
        );
    }

    if EXCLUDED_FUNCS.contains(&name) {
        return format!("{name} is a built-in helper function.");
    }

    let t = lookup_type(name);
    if !t.starts_with("Type '") {
        return t;
    }
    format!("Function or type '{name}' not found.")
}

pub fn search_with_lookups(query: &str) -> Vec<String> {
    let func_matches = get_func_matches(query);
    let type_matches = get_type_matches(query);
    let mut results = Vec::new();
    for m in func_matches {
        results.push(lookup_function(&m.name));
    }
    for m in type_matches {
        results.push(lookup_type(&m.name));
    }
    results
}

pub fn cli_help_output(pattern_or_method: Option<&str>) -> String {
    let Some(q) = pattern_or_method.filter(|s| !s.is_empty()) else {
        return get_readme().trim().to_string();
    };
    let exact = lookup_function(q);
    let summary = search_help(q);
    if exact.starts_with(&format!("Function or type '{q}' not found.")) {
        return summary;
    }
    let needle = format!(": {} (", q.to_lowercase());
    let other: Vec<&str> = summary
        .lines()
        .skip(1)
        .filter(|ln| !ln.to_lowercase().contains(&needle))
        .collect();
    if other.is_empty() {
        exact.trim().to_string()
    } else {
        format!(
            "{}\n\nOther matches for '{q}':\n{}",
            exact.trim(),
            other.join("\n")
        )
    }
}

