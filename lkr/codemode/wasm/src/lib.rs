struct ChattyState {
    port: Option<MessagePort>,
    initialized: bool,
    init_waiters: Vec<oneshot::Sender<Result<Value, String>>>,
    next_sequence: u32,
    pending_requests: BTreeMap<u32, oneshot::Sender<Result<Value, String>>>,
    host_data: Value,
    target_origin: Option<String>,
    _onmessage_closure: Option<Closure<dyn FnMut(MessageEvent)>>,
}

impl Default for ChattyState {
    fn default() -> Self {
        Self {
            port: None,
            initialized: false,
            init_waiters: Vec::new(),
            next_sequence: 1_000_000,
            pending_requests: BTreeMap::new(),
            host_data: Value::Object(Map::new()),
            target_origin: None,
            _onmessage_closure: None,
        }
    }
}

thread_local! {
    static CHATTY_STATE: RefCell<ChattyState> = RefCell::new(ChattyState::default());
}

fn js_to_json(val: &JsValue) -> Value {
    if val.is_undefined() || val.is_null() {
        return Value::Null;
    }
    js_sys::JSON::stringify(val)
        .ok()
        .and_then(|s| s.as_string())
        .and_then(|s| serde_json::from_str(&s).ok())
        .unwrap_or(Value::Null)
}

fn json_to_js(val: &Value) -> JsValue {
    if val.is_null() {
        return JsValue::NULL;
    }
    serde_json::to_string(val)
        .ok()
        .and_then(|s| js_sys::JSON::parse(&s).ok())
        .unwrap_or(JsValue::NULL)
}

fn extract_origin_from_url(url: &str) -> Option<String> {
    let trimmed = url.trim();
    if trimmed.is_empty() || trimmed == "null" {
        return None;
    }
    if trimmed == "*" {
        return Some("*".to_string());
    }
    if let Some(scheme_idx) = trimmed.find("://") {
        let rest = &trimmed[scheme_idx + 3..];
        let host_end = rest.find('/').unwrap_or(rest.len());
        let host = &rest[..host_end];
        if !host.is_empty() {
            return Some(format!("{}://{}", &trimmed[..scheme_idx], host));
        }
    }
    None
}

fn resolve_target_origin() -> String {
    CHATTY_STATE
        .with(|cell| {
            let st = cell.borrow();
            st.target_origin.clone().or_else(|| {
                st.host_data
                    .get("hostOrigin")
                    .or_else(|| st.host_data.get("hostUrl"))
                    .and_then(|v| v.as_str())
                    .and_then(extract_origin_from_url)
            })
        })
        .unwrap_or_else(|| "*".to_string())
}

fn unwrap_core_sdk_response(resp: Value) -> Result<Value, String> {
    if let Some(obj) = resp.as_object() {
        // RAW_INVOKE_CORE_SDK / transport.rawRequest response: { ok, statusCode, statusMessage, body, ... }
        if obj.contains_key("statusCode") || obj.contains_key("body") {
            let status = obj
                .get("statusCode")
                .and_then(|v| v.as_u64())
                .unwrap_or(200);
            let ok = obj.get("ok").and_then(|v| v.as_bool()).unwrap_or(true);
            let body_val = obj.get("body").cloned().unwrap_or(Value::Null);
            if !ok || status >= 400 {
                let err_str = match &body_val {
                    Value::String(s) => s.clone(),
                    other => other.to_string(),
                };
                return Err(format!("Looker API error ({status}): {err_str}"));
            }
            if let Value::String(s) = body_val {
                let trimmed = s.trim();
                if trimmed.is_empty() {
                    return Ok(Value::Null);
                }
                if trimmed.starts_with('{') || trimmed.starts_with('[') {
                    if let Ok(parsed) = serde_json::from_str::<Value>(trimmed) {
                        return Ok(parsed);
                    }
                }
                return Ok(Value::String(s));
            }
            return Ok(body_val);
        }
        // INVOKE_CORE_SDK response: { ok, value, error }
        if let Some(ok_bool) = obj.get("ok").and_then(|v| v.as_bool()) {
            if ok_bool {
                return Ok(obj.get("value").cloned().unwrap_or(Value::Null));
            }
            let err_val = obj.get("error").cloned().unwrap_or(Value::Null);
            let msg = err_val
                .get("message")
                .and_then(|v| v.as_str())
                .map(str::to_owned)
                .unwrap_or_else(|| match &err_val {
                    Value::String(s) => s.clone(),
                    other => other.to_string(),
                });
            return Err(msg);
        }
    }
    Ok(resp)
}

fn handle_chatty_port_message(ev: MessageEvent) {
    let msg = js_to_json(&ev.data());
    let Some(action) = msg.get("action").and_then(|v| v.as_i64()).map(|n| n as i32) else {
        return;
    };

    match action {
        CHATTY_HOST_SYN_ACK => {
            CHATTY_STATE.with(|cell| {
                if let Some(port) = &cell.borrow().port {
                    let ack = json_to_js(&json!({ "action": CHATTY_CLIENT_ACK, "data": {} }));
                    let _ = port.post_message(&ack);
                }
            });
        }
        CHATTY_HOST_MESSAGE_WITH_RESPONSE => {
            let Some(data) = msg.get("data") else { return };
            let event_name = data.get("eventName").and_then(|v| v.as_str()).unwrap_or("");
            let sequence = data.get("sequence").and_then(|v| v.as_u64()).unwrap_or(0) as u32;
            if event_name == "EXTENSION_NOTIFICATION" {
                let first_payload = data
                    .get("payload")
                    .and_then(|v| v.as_array())
                    .and_then(|a| a.first())
                    .cloned()
                    .unwrap_or(Value::Null);
                let notif_type = first_payload
                    .get("type")
                    .and_then(|v| v.as_str())
                    .unwrap_or("");

                if notif_type == "INITIALIZE" {
                    let mut host_data = first_payload
                        .get("payload")
                        .cloned()
                        .unwrap_or_else(|| json!({}));
                    if let Some(obj) = host_data.as_object_mut() {
                        obj.entry("mountPoint".to_string())
                            .or_insert_with(|| Value::String("standalone".to_string()));
                    }

                    let mut waiters = Vec::new();
                    let mut port_clone = None;
                    CHATTY_STATE.with(|cell| {
                        let mut st = cell.borrow_mut();
                        if let Some(orig) = host_data
                            .get("hostOrigin")
                            .or_else(|| host_data.get("hostUrl"))
                            .and_then(|v| v.as_str())
                            .and_then(extract_origin_from_url)
                        {
                            st.target_origin = Some(orig);
                        }
                        st.host_data = host_data.clone();
                        st.initialized = true;
                        waiters = std::mem::take(&mut st.init_waiters);
                        port_clone = st.port.clone();
                    });

                    if let Some(port) = port_clone {
                        let resp = json_to_js(&json!({
                            "action": CHATTY_CLIENT_RESPONSE,
                            "data": {
                                "eventName": "EXTENSION_NOTIFICATION",
                                "payload": [{ "extensionSdkVersion": "0.10.5" }],
                                "sequence": sequence
                            }
                        }));
                        let _ = port.post_message(&resp);
                    }

                    for w in waiters {
                        let _ = w.send(Ok(host_data.clone()));
                    }
                } else {
                    CHATTY_STATE.with(|cell| {
                        if let Some(port) = &cell.borrow().port {
                            let resp = json_to_js(&json!({
                                "action": CHATTY_CLIENT_RESPONSE,
                                "data": {
                                    "eventName": "EXTENSION_NOTIFICATION",
                                    "payload": [null],
                                    "sequence": sequence
                                }
                            }));
                            let _ = port.post_message(&resp);
                        }
                    });
                }
            }
        }
        CHATTY_HOST_RESPONSE => {
            let Some(data) = msg.get("data") else { return };
            let sequence = data.get("sequence").and_then(|v| v.as_u64()).unwrap_or(0) as u32;
            let payload_val = data
                .get("payload")
                .and_then(|v| v.as_array())
                .and_then(|a| a.first())
                .cloned()
                .unwrap_or(Value::Null);
            let sender =
                CHATTY_STATE.with(|cell| cell.borrow_mut().pending_requests.remove(&sequence));
            if let Some(tx) = sender {
                let _ = tx.send(unwrap_core_sdk_response(payload_val));
            }
        }
        CHATTY_HOST_RESPONSE_ERROR => {
            let Some(data) = msg.get("data") else { return };
            let sequence = data.get("sequence").and_then(|v| v.as_u64()).unwrap_or(0) as u32;
            let err_payload = data.get("payload").cloned().unwrap_or(Value::Null);
            let sender =
                CHATTY_STATE.with(|cell| cell.borrow_mut().pending_requests.remove(&sequence));
            if let Some(tx) = sender {
                let msg_str = match err_payload {
                    Value::String(s) => s,
                    other => other.to_string(),
                };
                let _ = tx.send(Err(msg_str));
            }
        }
        _ => {}
    }
}

async fn ensure_chatty_connected() -> Result<Value, String> {
    let already_init = CHATTY_STATE.with(|c| {
        let st = c.borrow();
        if st.initialized && st.port.is_some() {
            Some(st.host_data.clone())
        } else {
            None
        }
    });
    if let Some(hd) = already_init {
        return Ok(hd);
    }

    let (tx, rx) = oneshot::channel();
    let need_start = CHATTY_STATE.with(|cell| {
        let mut st = cell.borrow_mut();
        st.init_waiters.push(tx);
        st.port.is_none()
    });

    if need_start {
        let channel = MessageChannel::new()
            .map_err(|e| format!("Failed to create MessageChannel: {}", js_to_json(&e)))?;
        let port1 = channel.port1();
        let port2 = channel.port2();

        let closure =
            Closure::wrap(Box::new(handle_chatty_port_message) as Box<dyn FnMut(MessageEvent)>);
        port1.set_onmessage(Some(closure.as_ref().unchecked_ref()));
        port1.start();

        let target_origin = resolve_target_origin();
        let syn_msg = json_to_js(&json!({ "action": CHATTY_CLIENT_SYN }));
        let transfer = Array::new();
        transfer.push(&port2);

        let global = js_sys::global();
        let parent = Reflect::get(&global, &JsValue::from_str("parent"))
            .map_err(|_| "window.parent is not available".to_string())?;
        if parent.is_undefined() || parent.is_null() {
            return Err("window.parent is null or undefined; Looker Extension Host requires an iframe parent".to_string());
        }
        let post_fn = Reflect::get(&parent, &JsValue::from_str("postMessage"))
            .map_err(|_| "window.parent.postMessage is not available".to_string())?
            .dyn_into::<Function>()
            .map_err(|_| "window.parent.postMessage is not a function".to_string())?;

        post_fn
            .call3(
                &parent,
                &syn_msg,
                &JsValue::from_str(&target_origin),
                &transfer,
            )
            .map_err(|e| format!("window.parent.postMessage failed: {}", js_to_json(&e)))?;

        CHATTY_STATE.with(|cell| {
            let mut st = cell.borrow_mut();
            st.port = Some(port1);
            st._onmessage_closure = Some(closure);
        });
    }

    rx.await
        .map_err(|_| "Looker Extension Host connection cancelled".to_string())?
}

struct BrowserExtensionTransport {
    custom_handler: Option<Function>,
}

impl SdkTransport for BrowserExtensionTransport {
    fn invoke<'a>(
        &'a self,
        http_method: &'a str,
        path: &'a str,
        params: Option<Value>,
        body: Option<Value>,
        options: Option<Value>,
    ) -> Pin<Box<dyn Future<Output = Result<Value, String>> + 'a>> {
        Box::pin(async move {
            if let Some(handler) = &self.custom_handler {
                let args = Array::new();
                args.push(&JsValue::from_str(http_method));
                args.push(&JsValue::from_str(path));
                args.push(
                    &params
                        .as_ref()
                        .map(json_to_js)
                        .unwrap_or(JsValue::UNDEFINED),
                );
                args.push(&body.as_ref().map(json_to_js).unwrap_or(JsValue::UNDEFINED));
                args.push(
                    &options
                        .as_ref()
                        .map(json_to_js)
                        .unwrap_or(JsValue::UNDEFINED),
                );
                let ret = handler
                    .apply(&JsValue::NULL, &args)
                    .map_err(|e| format!("requestHandler error: {}", js_to_json(&e)))?;
                let resolved = if ret.is_instance_of::<Promise>() {
                    JsFuture::from(Promise::from(ret))
                        .await
                        .map_err(|e| format!("requestHandler rejected: {}", js_to_json(&e)))?
                } else {
                    ret
                };
                return unwrap_core_sdk_response(js_to_json(&resolved));
            }

            ensure_chatty_connected().await?;

            let (tx, rx) = oneshot::channel();
            let send_res: Result<(), String> = CHATTY_STATE.with(|cell| {
                let mut st = cell.borrow_mut();
                let seq = st.next_sequence;
                st.next_sequence += 1;
                let Some(port) = st.port.clone() else {
                    return Err("Chatty MessagePort is not connected".to_string());
                };
                // ponytail: use RAW_INVOKE_CORE_SDK so manifest.lkml only needs `raw_api_request: yes` instead of listing every SDK method in `core_api_methods`
                let msg = json_to_js(&json!({
                    "action": CHATTY_CLIENT_MESSAGE_WITH_RESPONSE,
                    "data": {
                        "eventName": "EXTENSION_API_REQUEST",
                        "payload": [{
                            "type": "RAW_INVOKE_CORE_SDK",
                            "payload": {
                                "httpMethod": http_method,
                                "path": path,
                                "params": params,
                                "body": body,
                                "options": options,
                                "apiVersion": "4.0"
                            }
                        }],
                        "sequence": seq
                    }
                }));
                st.pending_requests.insert(seq, tx);
                port.post_message(&msg)
                    .map_err(|e| format!("MessagePort.postMessage failed: {}", js_to_json(&e)))
            });
            send_res?;

            rx.await
                .map_err(|_| "Chatty request channel closed unexpectedly".to_string())?
        })
    }

    fn host_data(&self) -> Value {
        CHATTY_STATE.with(|c| c.borrow().host_data.clone())
    }
}

