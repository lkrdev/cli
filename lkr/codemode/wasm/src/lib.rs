#[derive(Default, Clone)]
pub struct RunOptions {
    pub allow_update_session: bool,
    pub vars: BTreeMap<String, Value>,
}

pub async fn execute_python_code<T: SdkTransport>(
    code: &str,
    opts: &RunOptions,
    transport: &T,
) -> String {
    let mut full_code = String::new();
    for (k, v) in &opts.vars {
        if is_valid_py_ident(k) {
            if let Ok(serialized) = serde_json::to_string(v) {
                full_code.push_str(&format!("{k} = {serialized}\n"));
            }
        }
    }
    full_code.push_str(code);
    let rewritten = rewrite_sdk_attributes(&full_code);

    let runner = match MontyRun::new(rewritten, "main.py", vec![], CompileOptions::default()) {
        Ok(r) => r,
        Err(exc) => return format!("Error: {exc}"),
    };

    let mut stdout_buf = String::new();
    let mut progress = match runner.start(
        vec![],
        ResourceTracker::default(),
        PrintWriter::collect_string(&mut stdout_buf),
    ) {
        Ok(p) => p,
        Err(exc) => return format!("Error: {exc}"),
    };

    let meta = metadata();

    loop {
        match progress {
            RunProgress::NameLookup(lookup) => {
                let name = lookup.name.clone();
                let res = if let Some(builtin) = MontyObject::builtin_function_from_name(&name) {
                    NameLookupResult::Value(builtin)
                } else if meta.operations.contains_key(&name)
                    || EXCLUDED_FUNCS.contains(&name.as_str())
                    || meta.definitions.contains_key(&name)
                {
                    NameLookupResult::Value(MontyObject::function(name, None))
                } else {
                    NameLookupResult::Undefined
                };
                progress = match lookup.resume(res, PrintWriter::collect_string(&mut stdout_buf)) {
                    Ok(p) => p,
                    Err(exc) => return format!("Error: {exc}"),
                };
            }
            RunProgress::FunctionCall(call) => {
                let fname = call.function_name.clone();
                let pos_args: Vec<Value> = call.args.args().map(monty_ref_to_json).collect();
                let mut kw_args = Map::new();
                for (k, v) in call.args.kwargs() {
                    if let Some(ks) = k.as_str() {
                        kw_args.insert(ks.to_string(), monty_ref_to_json(v));
                    }
                }

                let call_result: ExtFunctionResult = match fname.as_str() {
                    "dir" => ExtFunctionResult::Return(MontyObject::list(
                        dir_list().into_iter().map(MontyObject::string),
                    )),
                    "help" => {
                        let q = pos_args
                            .first()
                            .or_else(|| kw_args.get("query"))
                            .and_then(|v| v.as_str())
                            .unwrap_or("");
                        ExtFunctionResult::Return(MontyObject::string(search_help(q)))
                    }
                    "lookup" => {
                        let Some(q) = pos_args
                            .first()
                            .or_else(|| kw_args.get("name"))
                            .and_then(|v| v.as_str())
                        else {
                            return "Error: lookup() missing required argument 'name'".to_string();
                        };
                        ExtFunctionResult::Return(MontyObject::string(lookup_function(q)))
                    }
                    "search_with_lookups" => {
                        let Some(q) = pos_args
                            .first()
                            .or_else(|| kw_args.get("query"))
                            .and_then(|v| v.as_str())
                        else {
                            return "Error: search_with_lookups() missing required argument 'query'"
                                .to_string();
                        };
                        let items = search_with_lookups(q).into_iter().map(MontyObject::string);
                        ExtFunctionResult::Return(MontyObject::list(items))
                    }
                    "lookup_type" => {
                        let Some(q) = pos_args
                            .first()
                            .or_else(|| kw_args.get("type_name"))
                            .and_then(|v| v.as_str())
                        else {
                            return "Error: lookup_type() missing required argument 'type_name'"
                                .to_string();
                        };
                        ExtFunctionResult::Return(MontyObject::string(lookup_type(q)))
                    }
                    "examples" => ExtFunctionResult::Return(json_to_monty(&get_examples())),
                    "readme" => ExtFunctionResult::Return(MontyObject::string(get_readme())),
                    "host_data" => ExtFunctionResult::Return(json_to_monty(&transport.host_data())),
                    "update_session" if !opts.allow_update_session => {
                        ExtFunctionResult::Error(MontyException::new(
                            ExcType::RuntimeError,
                            Some(UPDATE_SESSION_BLOCKED_MSG.to_string()),
                        ))
                    }
                    other => {
                        if let Some(op) = meta.operations.get(other) {
                            match execute_sdk_operation(transport, op, &pos_args, &kw_args).await {
                                Ok(val) => ExtFunctionResult::Return(json_to_monty(&val)),
                                Err(err_msg) => ExtFunctionResult::Error(MontyException::new(
                                    ExcType::RuntimeError,
                                    Some(err_msg),
                                )),
                            }
                        } else if meta.definitions.contains_key(other) {
                            // Allow model constructor calls like WriteQuery(model="...", view="...") -> dict
                            let mut obj = kw_args;
                            if let Some(Value::Object(first_map)) = pos_args.first() {
                                for (k, v) in first_map {
                                    obj.entry(k.clone()).or_insert_with(|| v.clone());
                                }
                            }
                            ExtFunctionResult::Return(json_to_monty(&Value::Object(obj)))
                        } else {
                            ExtFunctionResult::Error(MontyException::new(
                                ExcType::NameError,
                                Some(format!("name '{other}' is not defined")),
                            ))
                        }
                    }
                };

                progress =
                    match call.resume(call_result, PrintWriter::collect_string(&mut stdout_buf)) {
                        Ok(p) => p,
                        Err(exc) => return format!("Error: {exc}"),
                    };
            }
            RunProgress::Complete(final_obj) => {
                let result_val = monty_ref_to_json(final_obj.as_ref());
                if !stdout_buf.is_empty() {
                    return serde_json::to_string_pretty(&json!({
                        "stdout": stdout_buf,
                        "result": result_val
                    }))
                    .unwrap_or_default();
                }
                return match result_val {
                    Value::Null => String::new(),
                    Value::String(s) => s,
                    other => {
                        serde_json::to_string_pretty(&other).unwrap_or_else(|_| final_obj.py_repr())
                    }
                };
            }
            RunProgress::OsCall(os_call) => {
                let exc = MontyException::new(
                    ExcType::PermissionError,
                    Some("OS calls are not permitted inside Looker Code Mode sandbox".to_string()),
                );
                progress = match os_call.resume(exc, PrintWriter::collect_string(&mut stdout_buf)) {
                    Ok(p) => p,
                    Err(e) => return format!("Error: {e}"),
                };
            }
            RunProgress::ResolveFutures(_) => {
                return "Error: Unsupported async future state in sandbox".to_string();
            }
        }
    }
}

