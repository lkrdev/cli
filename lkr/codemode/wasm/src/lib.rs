#[wasm_bindgen(js_name = setHostData)]
pub fn js_set_host_data(host_data: JsValue, target_origin: Option<String>) {
    let hd_json = js_to_json(&host_data);
    CHATTY_STATE.with(|cell| {
        let mut st = cell.borrow_mut();
        st.target_origin = target_origin.as_deref().and_then(extract_origin_from_url);
        if hd_json.is_object() {
            st.host_data = hd_json;
        } else if st.port.is_none() {
            st.host_data = Value::Object(Map::new());
        }
    });
}

#[wasm_bindgen(js_name = getHostData)]
pub fn js_get_host_data() -> JsValue {
    let hd = CHATTY_STATE.with(|c| c.borrow().host_data.clone());
    json_to_js(&hd)
}

#[wasm_bindgen(js_name = connectHost)]
pub fn js_connect_host() -> Promise {
    future_to_promise(async move {
        let hd = ensure_chatty_connected()
            .await
            .map_err(|e| JsValue::from_str(&e))?;
        Ok(json_to_js(&hd))
    })
}

#[wasm_bindgen(js_name = runPythonCodeRaw)]
pub fn js_run_python_code_raw(
    code: String,
    vars_json: Option<String>,
    allow_update_session: bool,
    custom_handler: Option<Function>,
) -> Promise {
    let mut run_opts = RunOptions {
        allow_update_session,
        vars: BTreeMap::new(),
    };
    if let Some(vj) = vars_json {
        if let Ok(Value::Object(map)) = serde_json::from_str::<Value>(&vj) {
            run_opts.vars.extend(map);
        }
    }
    let transport = BrowserExtensionTransport { custom_handler };
    future_to_promise(async move {
        let out = execute_python_code(&code, &run_opts, &transport).await;
        Ok(JsValue::from_str(&out))
    })
}

