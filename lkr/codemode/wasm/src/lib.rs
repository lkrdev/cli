pub fn monty_ref_to_json(obj: ObjectRef<'_>) -> Value {
    match obj.type_name() {
        "NoneType" => Value::Null,
        "bool" => Value::Bool(obj.as_bool().unwrap_or(false)),
        "int" => {
            if let Some(i) = obj.as_int() {
                Value::Number(i.into())
            } else {
                Value::String(obj.to_string())
            }
        }
        "float" => {
            if let Some(f) = obj.as_float().and_then(serde_json::Number::from_f64) {
                Value::Number(f)
            } else {
                Value::Null
            }
        }
        "str" => Value::String(obj.as_str().unwrap_or("").to_string()),
        "list" | "tuple" | "set" | "frozenset" => {
            if let Some(items) = obj.items() {
                Value::Array(items.into_iter().map(monty_ref_to_json).collect())
            } else {
                Value::Array(vec![])
            }
        }
        other => {
            if let Some(pairs) = obj.pairs() {
                Value::Object(
                    pairs
                        .into_iter()
                        .map(|(k, v)| {
                            (
                                k.as_str()
                                    .map(str::to_owned)
                                    .unwrap_or_else(|| k.to_string()),
                                monty_ref_to_json(v),
                            )
                        })
                        .collect(),
                )
            } else if other == "dict" {
                Value::Object(Map::new())
            } else {
                Value::String(obj.to_string())
            }
        }
    }
}

pub fn json_to_monty(val: &Value) -> MontyObject {
    match val {
        Value::Null => MontyObject::none(),
        Value::Bool(b) => MontyObject::bool(*b),
        Value::Number(n) => {
            if let Some(i) = n.as_i64() {
                MontyObject::int(i)
            } else if let Some(f) = n.as_f64() {
                MontyObject::float(f)
            } else {
                MontyObject::string(n.to_string())
            }
        }
        Value::String(s) => MontyObject::string(s.clone()),
        Value::Array(arr) => MontyObject::list(arr.iter().map(json_to_monty)),
        Value::Object(map) => MontyObject::dict(
            map.iter()
                .map(|(k, v)| (MontyObject::string(k.clone()), json_to_monty(v))),
        ),
    }
}

fn encode_path_param(val: &Value) -> String {
    let raw = match val {
        Value::String(s) => s.clone(),
        Value::Null => String::new(),
        other => other.to_string(),
    };
    let mut out = String::with_capacity(raw.len());
    for b in raw.bytes() {
        if b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_' | b'.' | b'~') {
            out.push(b as char);
        } else {
            out.push_str(&format!("%{b:02X}"));
        }
    }
    out
}

pub fn rewrite_sdk_attributes(code: &str) -> String {
    static RE: OnceLock<Regex> = OnceLock::new();
    let re =
        RE.get_or_init(|| Regex::new(r"\bsdk\.([a-zA-Z_][a-zA-Z0-9_]*)\b").expect("valid regex"));
    re.replace_all(code, "$1").into_owned()
}

fn is_valid_py_ident(s: &str) -> bool {
    let mut chars = s.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(first.is_ascii_alphabetic() || first == '_') {
        return false;
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

