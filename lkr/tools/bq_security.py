def _slug(text: str, max_len: int = 56) -> str:
    s = re.sub(r"[^a-zA-Z0-9_]+", "_", text.strip().lower()).strip("_")
    return s[:max_len].rstrip("_") or "sec"


def _normalize_policy_tag_key(tag_path: str) -> tuple[str, str, str] | None:
    m = re.search(
        r"locations/([^/]+)/taxonomies/([^/]+)/policyTags/([^/]+)",
        tag_path,
    )
    if not m:
        return None
    return (m.group(1).lower(), m.group(2), m.group(3))


def _taxonomy_from_policy_tag(tag_path: str) -> str | None:
    m = re.match(r"^(projects/[^/]+/locations/[^/]+/taxonomies/[^/]+)", tag_path)
    return m.group(1) if m else None


def resolve_gcp_token(explicit_token: str | None = None) -> str:
    token = (
        explicit_token
        or os.getenv("GCP_ACCESS_TOKEN")
        or os.getenv("GOOGLE_OAUTH_ACCESS_TOKEN")
    )
    if token:
        return token.strip()
    for cmd in (
        ["gcloud", "auth", "application-default", "print-access-token"],
        ["gcloud", "auth", "print-access-token"],
    ):
        try:
            proc = subprocess.run(
                cmd, capture_output=True, text=True, check=False, timeout=15
            )
            if proc.returncode == 0 and proc.stdout.strip():
                return proc.stdout.strip()
        except Exception as e:  # noqa: BLE001
            logger.debug(f"gcloud token probe notice ({cmd[0]}): {e}")
    raise ValueError(
        "No GCP access token available. Pass --gcp-token or set GCP_ACCESS_TOKEN."
    )


def _extract_denied_permission(payload: Any, raw_text: str) -> tuple[str | None, str | None, str]:
    msg = raw_text.strip()
    perm: str | None = None
    resource: str | None = None
    if isinstance(payload, dict):
        err = payload.get("error")
        if isinstance(err, dict):
            msg = str(err.get("message") or msg)
            for det in err.get("details") or []:
                if not isinstance(det, dict):
                    continue
                meta = det.get("metadata")
                if isinstance(meta, dict):
                    perm = perm or meta.get("permission")
                    resource = resource or meta.get("resource")
    if not perm:
        m = re.search(
            r"Permission ['\"\[]?([a-zA-Z0-9_.]+)['\"\]]? denied",
            msg,
        ) or re.search(r"permission \[([a-zA-Z0-9_.]+)\]", msg)
        if m:
            perm = m.group(1)
    return perm, resource, msg


def _gcp_request(
    method: str,
    url: str,
    token: str,
    *,
    json_body: dict[str, Any] | None = None,
    session: requests.Session | None = None,
) -> dict[str, Any]:
    http = session or requests
    resp = http.request(
        method,
        url,
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
        },
        json=json_body,
        timeout=25,
    )
    if resp.status_code == 403:
        try:
            payload = resp.json()
        except Exception:  # noqa: BLE001
            payload = None
        perm, res, msg = _extract_denied_permission(payload, resp.text)
        raise BqPermissionDeniedError(
            endpoint=url,
            status_code=403,
            permission=perm,
            resource=res,
            raw_message=msg,
        )
    if not resp.ok:
        raise RuntimeError(
            f"GCP API error ({resp.status_code}) on {method} {url}: {resp.text[:500]}"
        )
    return resp.json() if resp.text.strip() else {}


def _parse_member_Into_principals(
    member: str,
    out: BqPrincipals,
    excluded_service_accounts: set[str],
) -> None:
    m = member.strip()
    if m.startswith("deleted:"):
        return
    if m in ("allUsers", "allAuthenticatedUsers", "iamMember:allUsers", "iamMember:allAuthenticatedUsers"):
        out.public = True
        return
    m = m.removeprefix("iamMember:")
    if m.startswith("serviceAccount:"):
        # Service accounts do not map to interactive Looker human users/groups.
        return
    if m.startswith("group:"):
        out.groups.add(m.split(":", 1)[1])
    elif m.startswith("user:"):
        out.users.add(m.split(":", 1)[1])
    elif m.startswith("domain:"):
        out.public = True


def _extract_iam_principals(
    iam_policy: dict[str, Any],
    allowed_roles: frozenset[str],
    excluded_service_accounts: set[str],
) -> tuple[BqPrincipals, bool]:
    """Return (human principals, saw_any_explicit_human_binding)."""
    out = BqPrincipals()
    saw_human = False
    for binding in iam_policy.get("bindings") or []:
        if not isinstance(binding, dict):
            continue
        role = str(binding.get("role") or "")
        if role not in allowed_roles:
            continue
        for member in binding.get("members") or []:
            m_str = str(member)
            if not m_str.startswith(("serviceAccount:", "deleted:")):
                saw_human = True
            _parse_member_Into_principals(m_str, out, excluded_service_accounts)
    return out, saw_human


def _flatten_bq_fields(
    fields: list[dict[str, Any]],
    prefix_dot: str = "",
    prefix_lkml: str = "",
) -> list[tuple[str, str, str, str | None, list[str]]]:
    """Return list of (dot_path, lookml_col, bq_type, policy_tag, data_policies)."""
    out: list[tuple[str, str, str, str | None, list[str]]] = []
    for f in fields:
        if not isinstance(f, dict) or not f.get("name"):
            continue
        name = str(f["name"])
        dot_path = f"{prefix_dot}.{name}" if prefix_dot else name
        lkml_col = f"{prefix_lkml}__{name}" if prefix_lkml else name
        bq_type = str(f.get("type") or "STRING").upper()
        subfields = f.get("fields")
        if bq_type in ("RECORD", "STRUCT") and isinstance(subfields, list) and subfields:
            out.extend(_flatten_bq_fields(subfields, dot_path, lkml_col))
            continue
        pt_names = ((f.get("policyTags") or {}).get("names")) or []
        pt = str(pt_names[0]) if pt_names else None
        dp_list = [
            str(dp.get("name"))
            for dp in (f.get("dataPolicies") or [])
            if isinstance(dp, dict) and dp.get("name")
        ]
        out.append((dot_path, lkml_col, bq_type, pt, dp_list))
    return out


def discover_bq_security(
    *,
    project_id: str,
    dataset_id: str,
    table_ids: list[str],
    token: str,
    excluded_service_accounts: set[str] | None = None,
    session: requests.Session | None = None,
) -> dict[str, BqTableSecurity]:
    """Discover Dataset ACLs, Table IAM, Row Access Policies, Policy Tags, and Masking (fail-closed on 403)."""
    excl_sa = {s.lower() for s in (excluded_service_accounts or set())}
    ds_base = (
        f"https://bigquery.googleapis.com/bigquery/v2/projects/"
        f"{quote(project_id, safe='')}/datasets/{quote(dataset_id, safe='')}"
    )
    ds_meta = _gcp_request("GET", ds_base, token, session=session)
    location = str(ds_meta.get("location") or "us").lower()

    ds_readers = BqPrincipals()
    has_custom_ds_acl = False
    for acc in ds_meta.get("access") or []:
        if not isinstance(acc, dict):
            continue
        role = str(acc.get("role") or "")
        if role not in _DATA_READER_ROLES:
            continue
        if acc.get("specialGroup") in _INFRA_SPECIAL_GROUPS:
            continue
        if acc.get("specialGroup") == "allAuthenticatedUsers":
            ds_readers.public = True
            has_custom_ds_acl = True
        elif acc.get("groupByEmail"):
            ds_readers.groups.add(str(acc["groupByEmail"]))
            has_custom_ds_acl = True
        elif acc.get("userByEmail"):
            u = str(acc["userByEmail"])
            if not u.endswith(".gserviceaccount.com") and u.lower() not in excl_sa:
                ds_readers.users.add(u)
                has_custom_ds_acl = True
        elif acc.get("domain"):
            ds_readers.public = True
            has_custom_ds_acl = True
        elif acc.get("iamMember"):
            m_str = str(acc["iamMember"])
            if not m_str.startswith(("serviceAccount:", "deleted:")):
                has_custom_ds_acl = True
            _parse_member_Into_principals(m_str, ds_readers, excl_sa)

    ds_iam_url = (
        f"https://bigquery.googleapis.com/bigquery/v2/projects/"
        f"{quote(project_id, safe='')}/datasets/{quote(dataset_id, safe='')}:getIamPolicy"
    )
    ds_iam = _gcp_request("POST", ds_iam_url, token, json_body={}, session=session)
    ds_iam_readers, saw_ds_iam_human = _extract_iam_principals(
        ds_iam,
        _DATA_READER_ROLES,
        excl_sa,
    )
    # Ignore default project-level OWNER/WRITER/READER mirror bindings in :getIamPolicy unless a non-basic role or group/user was explicitly added
    ds_readers = ds_readers.union(ds_iam_readers)
    has_custom_ds_acl = has_custom_ds_acl or (
        saw_ds_iam_human and not ds_iam_readers.is_empty()
    )

    raw_tables: dict[str, BqTableSecurity] = {}
    all_policy_tags: set[str] = set()

    for tbl_id in table_ids:
        tbl_url = f"{ds_base}/tables/{quote(tbl_id, safe='')}"
        tbl_meta = _gcp_request("GET", tbl_url, token, session=session)
        tbl_iam = _gcp_request(
            "POST", f"{tbl_url}:getIamPolicy", token, json_body={}, session=session
        )
        tbl_only_readers, saw_tbl_human = _extract_iam_principals(
            tbl_iam, _DATA_READER_ROLES, excl_sa
        )
        effective_readers = ds_readers.union(tbl_only_readers)
        has_custom_iam = (saw_tbl_human or has_custom_ds_acl) and not effective_readers.public

        cols: dict[str, BqColumnSecurity] = {}
        schema_fields = ((tbl_meta.get("schema") or {}).get("fields")) or []
        for dot_path, lkml_col, bq_type, pt, _dp_list in _flatten_bq_fields(schema_fields):
            if pt:
                all_policy_tags.add(pt)
            cols[lkml_col.lower()] = BqColumnSecurity(
                col_path=dot_path,
                lookml_col=lkml_col,
                bq_type=bq_type,
                policy_tag=pt,
            )

        rap_resp = _gcp_request(
            "GET", f"{tbl_url}/rowAccessPolicies", token, session=session
        )
        raps: list[BqRowPolicy] = []
        for rap in rap_resp.get("rowAccessPolicies") or []:
            if not isinstance(rap, dict):
                continue
            ref = rap.get("rowAccessPolicyReference") or {}
            pid = str(ref.get("policyId") or "")
            pred = str(rap.get("filterPredicate") or "FALSE")
            grantees = BqPrincipals()
            saw_non_sa = False
            for g in rap.get("grantees") or []:
                g_str = str(g)
                if not g_str.startswith(("serviceAccount:", "iamMember:serviceAccount:", "deleted:")):
                    saw_non_sa = True
                _parse_member_Into_principals(g_str, grantees, excl_sa)
            if pid:
                rap_iam = _gcp_request(
                    "POST",
                    f"{tbl_url}/rowAccessPolicies/{quote(pid, safe='')}:getIamPolicy",
                    token,
                    json_body={},
                    session=session,
                )
                iam_grantees, iam_human = _extract_iam_principals(
                    rap_iam, _RAP_READER_ROLES, excl_sa
                )
                grantees = grantees.union(iam_grantees)
                saw_non_sa = saw_non_sa or iam_human
            # Skip pure runtime-SA bypass RAPs (e.g. Looker SA FILTER USING (TRUE)) that have zero human grantees
            if not saw_non_sa and grantees.is_empty():
                continue
            raps.append(
                BqRowPolicy(
                    policy_id=pid,
                    filter_predicate=pred,
                    grantees=grantees,
                )
            )

        raw_tables[tbl_id.lower()] = BqTableSecurity(
            project_id=project_id,
            dataset_id=dataset_id,
            table_id=tbl_id,
            has_custom_table_iam=has_custom_iam,
            table_readers=effective_readers,
            columns=cols,
            row_policies=raps,
        )

    if all_policy_tags:
        tag_readers_cache: dict[str, BqPrincipals] = {}
        tax_readers_cache: dict[str, BqPrincipals] = {}
        for pt in sorted(all_policy_tags):
            tax = _taxonomy_from_policy_tag(pt)
            if tax and tax not in tax_readers_cache:
                tax_iam = _gcp_request(
                    "POST",
                    f"https://datacatalog.googleapis.com/v1/{tax}:getIamPolicy",
                    token,
                    json_body={},
                    session=session,
                )
                tax_p, _ = _extract_iam_principals(
                    tax_iam, _FINE_GRAINED_READER_ROLES, excl_sa
                )
                tax_readers_cache[tax] = tax_p
            pt_iam = _gcp_request(
                "POST",
                f"https://datacatalog.googleapis.com/v1/{pt}:getIamPolicy",
                token,
                json_body={},
                session=session,
            )
            pt_p, _ = _extract_iam_principals(
                pt_iam, _FINE_GRAINED_READER_ROLES, excl_sa
            )
            base_tax_p = tax_readers_cache.get(tax or "", BqPrincipals())
            tag_readers_cache[pt] = base_tax_p.union(pt_p)

        dp_list_url = (
            f"https://bigquerydatapolicy.googleapis.com/v1/projects/"
            f"{quote(project_id, safe='')}/locations/{quote(location, safe='')}/dataPolicies"
        )
        dp_resp = _gcp_request("GET", dp_list_url, token, session=session)
        mask_by_tag_key: dict[tuple[str, str, str], tuple[str, BqPrincipals]] = {}
        wanted_keys = {
            k for pt in all_policy_tags if (k := _normalize_policy_tag_key(pt)) is not None
        }
        for dp in dp_resp.get("dataPolicies") or []:
            if not isinstance(dp, dict):
                continue
            if dp.get("dataPolicyType") != "DATA_MASKING_POLICY":
                continue
            dp_tag = str(dp.get("policyTag") or "")
            t_key = _normalize_policy_tag_key(dp_tag)
            if not t_key or t_key not in wanted_keys:
                continue
            expr = str(
                ((dp.get("dataMaskingPolicy") or {}).get("predefinedExpression")) or ""
            )
            dp_name = str(dp.get("name") or "")
            if not expr or not dp_name:
                continue
            dp_iam = _gcp_request(
                "POST",
                f"https://bigquerydatapolicy.googleapis.com/v1/{dp_name}:getIamPolicy",
                token,
                json_body={},
                session=session,
            )
            m_principals, _ = _extract_iam_principals(
                dp_iam, _MASKED_READER_ROLES, excl_sa
            )
            if t_key in mask_by_tag_key:
                prev_expr, prev_p = mask_by_tag_key[t_key]
                mask_by_tag_key[t_key] = (prev_expr, prev_p.union(m_principals))
            else:
                mask_by_tag_key[t_key] = (expr, m_principals)

        for tsec in raw_tables.values():
            for csec in tsec.columns.values():
                if not csec.policy_tag:
                    continue
                csec.unmasked_readers = tag_readers_cache.get(
                    csec.policy_tag, BqPrincipals()
                )
                t_key = _normalize_policy_tag_key(csec.policy_tag)
                if t_key and t_key in mask_by_tag_key:
                    csec.mask_expression, csec.masked_readers = mask_by_tag_key[t_key]

    return raw_tables


def _bq_mask_sql(col_sql: str, bq_type: str, mask_expr: str) -> str:
    t = bq_type.upper()
    m = mask_expr.upper()
    if m == "SHA256":
        return (
            f"SHA256({col_sql})"
            if t == "BYTES"
            else f"TO_HEX(SHA256(CAST({col_sql} AS STRING)))"
        )
    if m == "LAST_FOUR_CHARACTERS":
        return f"CONCAT('XXXXX', RIGHT(CAST({col_sql} AS STRING), 4))"
    if m == "FIRST_FOUR_CHARACTERS":
        return f"CONCAT(LEFT(CAST({col_sql} AS STRING), 4), 'XXXXX')"
    if m == "EMAIL_MASK":
        return f"REGEXP_REPLACE(CAST({col_sql} AS STRING), r'^[^@]+', 'XXXXX')"
    if m == "DATE_YEAR_MASK":
        return f"DATE_TRUNC({col_sql}, YEAR)"
    if m == "DEFAULT_MASKING_VALUE":
        if t in _NUMERIC_BQ_TYPES:
            return "0"
        return {
            "BOOL": "FALSE",
            "BOOLEAN": "FALSE",
            "DATE": "DATE '1970-01-01'",
            "DATETIME": "DATETIME '1970-01-01 00:00:00'",
            "TIMESTAMP": "TIMESTAMP('1970-01-01 00:00:00 UTC')",
        }.get(t, "''")
    # ALWAYS_NULL or unknown fallback -> fail-closed NULL
    sql_t = "INT64" if t == "INTEGER" else "FLOAT64" if t == "FLOAT" else t
    return f"CAST(NULL AS {sql_t})"


def _escape_looker_filter_val(val: str, is_numeric: bool) -> str:
    return val if is_numeric else re.sub(r'(^[- ]|["%_,^])', r"^\1", val)


@dataclass
class _ParsedRap:
    kind: Literal["true", "session_user", "values", "complex"]
    column: str | None = None
    values: list[str] = field(default_factory=list)
    raw_sql: str = ""
    grantees: BqPrincipals = field(default_factory=BqPrincipals)


def _parse_rap_predicate(rap: BqRowPolicy) -> _ParsedRap:
    raw = rap.filter_predicate.strip()
    try:
        node = sqlglot.parse_one(raw, read="bigquery")
    except SqlglotError:
        return _ParsedRap(kind="complex", raw_sql=raw, grantees=rap.grantees)

    while isinstance(node, exp.Paren):
        node = node.this

    if isinstance(node, exp.Boolean) and node.this is True:
        return _ParsedRap(kind="true", raw_sql=raw, grantees=rap.grantees)

    if isinstance(node, exp.EQ):
        for col_node, val_node in ((node.left, node.right), (node.right, node.left)):
            if not isinstance(col_node, exp.Column):
                continue
            if (
                isinstance(val_node, exp.Anonymous)
                and val_node.name.upper() == "SESSION_USER"
                or val_node.sql("bigquery").upper() == "SESSION_USER()"
            ):
                return _ParsedRap(
                    kind="session_user",
                    column=col_node.name.lower(),
                    raw_sql=raw,
                    grantees=rap.grantees,
                )
            if isinstance(val_node, exp.Literal):
                return _ParsedRap(
                    kind="values",
                    column=col_node.name.lower(),
                    values=[str(val_node.this)],
                    raw_sql=raw,
                    grantees=rap.grantees,
                )

    if isinstance(node, exp.In) and isinstance(node.this, exp.Column):
        exprs = node.expressions or []
        if exprs and all(isinstance(e, exp.Literal) for e in exprs):
            return _ParsedRap(
                kind="values",
                column=node.this.name.lower(),
                values=[str(e.this) for e in exprs],
                raw_sql=raw,
                grantees=rap.grantees,
            )

    return _ParsedRap(kind="complex", raw_sql=raw, grantees=rap.grantees)


def _match_view_field_for_bq_col(
    view: LookmlView, col: BqColumnSecurity
) -> list[tuple[Literal["dimension", "dimension_group"], str, str]]:
    """Return list of (field_kind, field_name, sql_expr) matching `col` in `view`."""
    matches: list[tuple[Literal["dimension", "dimension_group"], str, str]] = []
    candidates = [col.lookml_col, col.col_path]
    stripped_time_names = {
        col.lookml_col.lower()[: -len(sfx)]
        for sfx in _TIME_SUFFIXES
        if col.lookml_col.lower().endswith(sfx)
        and len(col.lookml_col) > len(sfx)
    }

    for d_name, d_obj in (view.dimension or {}).items():
        if any(
            _field_matches_column(cand, d_name, d_obj.sql, "dimension")
            for cand in candidates
        ):
            matches.append(
                (
                    "dimension",
                    d_name,
                    (d_obj.sql or f"${{TABLE}}.{col.col_path}").strip(),
                )
            )

    for dg_name, dg_obj in (view.dimension_group or {}).items():
        tfs = list(dg_obj.timeframes or [])
        if (
            any(
                _field_matches_column(
                    cand, dg_name, dg_obj.sql, "dimension_group", tfs
                )
                for cand in candidates
            )
            or dg_name.lower() in stripped_time_names
        ):
            matches.append(
                (
                    "dimension_group",
                    dg_name,
                    (dg_obj.sql or f"${{TABLE}}.{col.col_path}").strip(),
                )
            )
    return matches


def _register_bool_grant(
    grant_name: str,
    attr_name: str,
    principals: BqPrincipals,
    attrs: dict[str, DesiredAttributeSpec],
    grants: dict[str, str],
) -> None:
    grants[grant_name] = attr_name
    spec = attrs.setdefault(
        attr_name,
        DesiredAttributeSpec(
            name=attr_name,
            attr_type="string",
            default_value="yes" if principals.public else "no",
        ),
    )
    if principals.public:
        spec.default_value = "yes"
    for g in sorted(principals.groups):
        spec.groups[g] = "yes"
    for u in sorted(principals.users):
        spec.users[u] = "yes"


@dataclass
class _TableRlsPlan:
    mode: Literal["none", "access_filter", "sql_always_where"] = "none"
    bq_col: str | None = None
    is_numeric: bool = False
    user_attribute: str | None = None
    uses_session_user_only: bool = False
    full_bypass_grant: str | None = None
    sql_template: str | None = None  # uses `{ALIAS}` placeholder for table/join alias


def _build_table_rls_plan(
    tsec: BqTableSecurity,
    attrs: dict[str, DesiredAttributeSpec],
    grants: dict[str, str],
) -> _TableRlsPlan:
    if not tsec.row_policies:
        return _TableRlsPlan(mode="none")

    parsed = [_parse_rap_predicate(r) for r in tsec.row_policies]
    true_principals = BqPrincipals()
    for p in parsed:
        if p.kind == "true":
            true_principals = true_principals.union(p.grantees)

    full_grant: str | None = None
    if not true_principals.is_empty():
        full_attr = _slug(f"bq_rls_all_{tsec.dataset_id}_{tsec.table_id}")
        full_grant = full_attr
        _register_bool_grant(full_grant, full_attr, true_principals, attrs, grants)

    non_true = [p for p in parsed if p.kind != "true"]
    cols = {p.column for p in non_true if p.column}
    all_simple = all(p.kind in ("true", "session_user", "values") for p in parsed)

    if all_simple and len(cols) <= 1:
        target_col = next(iter(cols), None)
        if target_col is None:
            # Only `TRUE` RAPs exist on this table -> require membership in the TRUE RAP grant!
            assert full_grant is not None
            return _TableRlsPlan(
                mode="sql_always_where",
                full_bypass_grant=full_grant,
                sql_template=(
                    f"{{% if _user_attributes['{full_grant}'] == 'yes' %}}TRUE"
                    f"{{% else %}}FALSE{{% endif %}}"
                ),
            )

        csec = tsec.columns.get(target_col.lower())
        is_num = bool(csec and csec.bq_type.upper() in _NUMERIC_BQ_TYPES)
        has_values = any(p.kind == "values" for p in non_true)
        has_sess = any(p.kind == "session_user" for p in non_true)

        # Pure SESSION_USER() without TRUE/value policies maps directly to Looker's built-in `email` user attribute!
        if has_sess and not has_values and true_principals.is_empty():
            sess_principals = BqPrincipals()
            for p in non_true:
                sess_principals = sess_principals.union(p.grantees)
            if sess_principals.public:
                return _TableRlsPlan(
                    mode="access_filter",
                    bq_col=target_col,
                    is_numeric=is_num,
                    user_attribute="email",
                    uses_session_user_only=True,
                )

        # Single-column multi-policy / group / TRUE union via `advanced_filter_string` / `advanced_filter_number`
        if not has_sess:
            attr_name = _slug(
                f"bq_rls_{tsec.dataset_id}_{tsec.table_id}_{target_col}"
            )
            wildcard_all = "NULL, (-inf, inf)" if is_num else "%,NULL"
            deny_val = ">0 AND <0" if is_num else "__BQ_RLS_DENY__"
            spec = DesiredAttributeSpec(
                name=attr_name,
                attr_type=(
                    "advanced_filter_number" if is_num else "advanced_filter_string"
                ),
                default_value=wildcard_all if true_principals.public else deny_val,
            )
            group_vals: dict[str, list[str]] = {}
            user_vals: dict[str, list[str]] = {}
            for p in non_true:
                escaped = [
                    _escape_looker_filter_val(v, is_num) for v in p.values
                ]
                for g in p.grantees.groups:
                    group_vals.setdefault(g, []).extend(escaped)
                for u in p.grantees.users:
                    user_vals.setdefault(u, []).extend(escaped)
                if p.grantees.public:
                    spec.default_value = ",".join(dict.fromkeys(escaped))
            for g, vs in sorted(group_vals.items()):
                spec.groups[g] = ",".join(dict.fromkeys(vs))
            for u, vs in sorted(user_vals.items()):
                spec.users[u] = ",".join(dict.fromkeys(vs))
            for g in sorted(true_principals.groups):
                spec.groups[g] = wildcard_all
            for u in sorted(true_principals.users):
                spec.users[u] = wildcard_all
            attrs[attr_name] = spec

            # Also build `{ALIAS}` SQL guard for `LEFT OUTER` joins & `LEFT JOIN` PDT columns!
            branches = _build_liquid_rap_branches(
                tsec, parsed, attrs, grants
            )
            return _TableRlsPlan(
                mode="access_filter",
                bq_col=target_col,
                is_numeric=is_num,
                user_attribute=attr_name,
                full_bypass_grant=full_grant,
                sql_template=branches,
            )

    # Complex / multi-column OR SESSION_USER() mixed with group/TRUE RAPs -> Liquid OR composition
    sql_tpl = _build_liquid_rap_branches(tsec, parsed, attrs, grants)
    return _TableRlsPlan(
        mode="sql_always_where",
        bq_col=next(iter(cols), None) if len(cols) == 1 else None,
        full_bypass_grant=full_grant,
        sql_template=sql_tpl,
    )


def _rewrite_rap_sql_for_alias(raw_sql: str) -> str:
    try:
        node = sqlglot.parse_one(raw_sql, read="bigquery")
        if not node:
            return raw_sql
    except SqlglotError:
        return raw_sql

    def _xf(n: exp.Expr) -> exp.Expr:
        if isinstance(n, exp.Anonymous) and n.name.upper() == "SESSION_USER":
            return exp.Placeholder(this="__LKR_SESSION_EMAIL__")
        if n.sql("bigquery").upper() == "SESSION_USER()":
            return exp.Placeholder(this="__LKR_SESSION_EMAIL__")
        if isinstance(n, exp.Column) and not n.table:
            return exp.Column(
                this=n.this,
                table=exp.Identifier(this="__LKR_ALIAS__"),
            )
        return n

    rewritten = node.transform(_xf).sql("bigquery")
    rewritten = rewritten.replace("__LKR_ALIAS__.", "${{ALIAS}}.")
    rewritten = re.sub(
        r"\$\{\{ALIAS\}\}\.([a-zA-Z0-9_]+)",
        r"${{ALIAS}.\1}",
        rewritten,
    )
    rewritten = rewritten.replace(
        ":__LKR_SESSION_EMAIL__", "'{{ _user_attributes['email'] }}'"
    ).replace(
        "__LKR_SESSION_EMAIL__", "'{{ _user_attributes['email'] }}'"
    )
    return f"({rewritten})"


def _build_liquid_rap_branches(
    tsec: BqTableSecurity,
    parsed: list[_ParsedRap],
    attrs: dict[str, DesiredAttributeSpec],
    grants: dict[str, str],
) -> str:
    parts: list[str] = []
    for idx, p in enumerate(parsed):
        p_attr = _slug(
            f"bq_rap_{tsec.dataset_id}_{tsec.table_id}_{tsec.row_policies[idx].policy_id or idx}"
        )
        _register_bool_grant(p_attr, p_attr, p.grantees, attrs, grants)
        cond_sql = "TRUE" if p.kind == "true" else _rewrite_rap_sql_for_alias(p.raw_sql)
        parts.append(
            f"(case when '{{{{ _user_attributes[\"{p_attr}\"] }}}}' = 'yes' then {cond_sql} else FALSE end)"
        )
    return "(" + " OR ".join([*parts, "FALSE"]) + ")"


def _clean_lookml_dt_sql(sql: str) -> str:
    clean_sql = re.sub(r"\{%.*?%\}", "", sql, flags=re.DOTALL)
    clean_sql = re.sub(r"\{\{.*?\}\}", "1", clean_sql, flags=re.DOTALL)
    return re.sub(
        r"\$\{\s*([a-zA-Z0-9_]+)\.SQL_TABLE_NAME\s*\}",
        r"__lkml_tbl_\1",
        clean_sql,
        flags=re.IGNORECASE,
    )


def _resolve_tref_key(
    tref: TableRef,
    default_dataset: str,
    lower_phys: dict[str, tuple[str, str]],
) -> tuple[str, str]:
    nm = tref.name.strip("`\"' ").lower()
    if nm.startswith("__lkml_tbl_"):
        v_ref = nm.removeprefix("__lkml_tbl_")
        return lower_phys.get(v_ref, (default_dataset.lower(), v_ref))
    ds = (tref.db or default_dataset).strip("`\"' ").lower()
    return (ds, nm)


def _collect_all_views(proj: LookmlProject) -> dict[str, LookmlView]:
    view_base, _ = _collect_declarations(proj, "view", LookmlView)
    all_views: dict[str, LookmlView] = {
        v_name: v_val
        for m_obj in (proj.model or {}).values()
        for v_name, v_val in (m_obj.view or {}).items()
        if isinstance(v_val, LookmlView)
    }
    for v_name, decls in view_base.items():
        if v_name not in all_views and decls:
            all_views[v_name] = decls[-1][1].with_defaults()
    return all_views


def extract_project_bq_tables(
    project_files: dict[str, str], default_dataset: str
) -> set[str]:
    """Discover all BigQuery table names in `default_dataset` referenced by physical views and SQL derived tables via `lkr.parse`."""
    clean_files = {
        p: c
        for p, c in project_files.items()
        if not p.replace("\\", "/").startswith("security/")
    }
    if not clean_files:
        return set()
    all_views = _collect_all_views(_parse_virtual_project(clean_files))

    ds_low = default_dataset.lower()
    tables: set[str] = set()
    for v_name, v_obj in all_views.items():
        dt = v_obj.derived_table
        if dt is None:
            if v_obj.extends and not v_obj.sql_table_name:
                continue
            tref = _parse_lookml_table_name(v_obj.sql_table_name, v_name)
            if (tref.db or default_dataset).lower() == ds_low and tref.name:
                tables.add(tref.name)
        else:
            dt_sql = dt.get("sql") if isinstance(dt, dict) else dt.sql
            if isinstance(dt_sql, str) and dt_sql.strip():
                for sq in parse_sql(
                    sql=_clean_lookml_dt_sql(dt_sql),
                    dialect="bigquery",
                    default_schema=default_dataset,
                ).queries:
                    for t in sq.tables:
                        if (
                            not t.name.lower().startswith("__lkml_tbl_")
                            and (t.db or default_dataset).lower() == ds_low
                            and t.name
                        ):
                            tables.add(t.name)
    return tables


def _analyze_sql_dt_tables(
    sql: str,
    default_dataset: str,
    phys_view_table: dict[str, tuple[str, str]],
) -> tuple[
    set[tuple[str, str]],
    set[tuple[str, str]],
    dict[str, list[tuple[tuple[str, str], str, bool]]],
]:
    """Return (spine_tables, left_only_tables, out_col -> [((dataset, table), col, is_direct_passthrough)])."""
    clean_sql = _clean_lookml_dt_sql(sql)
    sql_res = parse_sql(
        sql=clean_sql, dialect="bigquery", default_schema=default_dataset
    )
    if not sql_res.queries or sql_res.queries[0].error:
        return set(), set(), {}
    q = sql_res.queries[0]
    try:
        parsed = sqlglot.parse_one(clean_sql, read="bigquery")
        if not parsed:
            return set(), set(), {}
    except SqlglotError:
        return set(), set(), {}

    lower_phys = {k.lower(): v for k, v in phys_view_table.items()}
    cte_names = {c.name.lower() for c in q.ctes}
    spine: set[tuple[str, str]] = set()
    left_candidates: dict[str, tuple[str, str]] = {}

    sub_queries = [
        q,
        *(
            sq
            for c in q.ctes
            for sq in parse_sql(
                sql=c.sql, dialect="bigquery", default_schema=default_dataset
            ).queries
            if not sq.error
        ),
    ]
    for sq in sub_queries:
        for j in sq.joins:
            if j.right_table and j.right_table.name.lower() not in cte_names:
                tk = _resolve_tref_key(j.right_table, default_dataset, lower_phys)
                al = (j.right_table.alias or j.right_table.name).lower()
                if j.join_type in ("LEFT", "LEFT OUTER"):
                    left_candidates[al] = tk
                else:
                    spine.add(tk)
            if (
                j.left_table
                and j.left_table.name.lower() not in (cte_names | {"unknown"})
                and (j.left_table.alias or j.left_table.name).lower()
                not in left_candidates
            ):
                spine.add(
                    _resolve_tref_key(j.left_table, default_dataset, lower_phys)
                )

        # Any LEFT JOIN alias referenced in WHERE or HAVING filters rows -> promote to spine!
        for clause_sql in (sq.where, sq.having):
            if not clause_sql:
                continue
            try:
                c_ast = sqlglot.parse_one(clause_sql, read="bigquery")
            except SqlglotError:
                continue
            for col_ref in c_ast.find_all(exp.Column):
                t_al = (col_ref.table or "").lower()
                if t_al in left_candidates:
                    spine.add(left_candidates.pop(t_al))

    left_vals = set(left_candidates.values())
    for t in q.tables:
        tk = _resolve_tref_key(t, default_dataset, lower_phys)
        if tk not in left_vals:
            spine.add(tk)
    left_only = left_vals - spine

    raw_lineage = _extract_dt_lineage(parsed, {})
    col_map: dict[str, list[tuple[tuple[str, str], str, bool]]] = {}
    direct_cols = {
        (c.alias or c.column).lower()
        for c in q.columns
        if c.column and not c.is_agg
    }

    for out_col, pairs in raw_lineage.items():
        is_direct = out_col in direct_cols and len(pairs) == 1
        for tbl_ref, src_col in pairs:
            if isinstance(tbl_ref, str):
                tk = lower_phys.get(
                    tbl_ref.lower(), (default_dataset.lower(), tbl_ref.lower())
                )
            else:
                tk = _resolve_tref_key(tbl_ref, default_dataset, lower_phys)
            col_map.setdefault(out_col, []).append((tk, src_col.lower(), is_direct))

    return spine, left_only, col_map


def compile_bq_security_overlays(
    *,
    project_files: dict[str, str],
    bq_tables: dict[str, BqTableSecurity],
    default_dataset: str,
    model_name: str | None = None,
) -> CompiledSecurityBundle:
    """Compile declarative `security/*.lkml` refinements and desired Looker User Attributes."""
    # Strip any prior autogenerated `security/*.lkml` files before parsing base LookML AST
    clean_files = {
        p: c
        for p, c in project_files.items()
        if not p.replace("\\", "/").startswith("security/")
    }
    tmp_project = _parse_virtual_project(clean_files)

    attrs: dict[str, DesiredAttributeSpec] = {}
    grants: dict[str, str] = {}
    warnings: list[str] = []

    by_ds_tbl: dict[tuple[str, str], BqTableSecurity] = {
        (t.dataset_id.lower(), t.table_id.lower()): t for t in bq_tables.values()
    }
    rls_plans: dict[tuple[str, str], _TableRlsPlan] = {
        k: _build_table_rls_plan(t, attrs, grants) for k, t in by_ds_tbl.items()
    }

    table_grants: dict[tuple[str, str], str] = {}
    col_unmasked_grants: dict[tuple[str, str, str], str] = {}
    col_read_or_mask_grants: dict[tuple[str, str, str], str] = {}

    for key, tsec in sorted(by_ds_tbl.items()):
        if tsec.has_custom_table_iam:
            g_name = _slug(f"bq_tbl_{tsec.dataset_id}_{tsec.table_id}")
            _register_bool_grant(g_name, g_name, tsec.table_readers, attrs, grants)
            table_grants[key] = g_name

        for col_low, csec in sorted(tsec.columns.items()):
            if not csec.policy_tag:
                continue
            t_norm = _normalize_policy_tag_key(csec.policy_tag)
            tag_slug = _slug(
                f"bq_tag_{t_norm[1]}_{t_norm[2]}" if t_norm else f"bq_tag_{col_low}"
            )
            _register_bool_grant(
                tag_slug, tag_slug, csec.unmasked_readers, attrs, grants
            )
            col_unmasked_grants[(*key, col_low)] = tag_slug

            if csec.mask_expression:
                rom_slug = _slug(f"bq_rom_{tsec.dataset_id}_{tsec.table_id}_{col_low}")
                both = csec.unmasked_readers.union(csec.masked_readers)
                _register_bool_grant(rom_slug, rom_slug, both, attrs, grants)
                col_read_or_mask_grants[(*key, col_low)] = rom_slug

    exp_base, exp_ref = _collect_declarations(tmp_project, "explore", LookmlExplore)
    assembled_models = tmp_project.model or {}
    all_views = _collect_all_views(tmp_project)

    # Map physical & extended views -> (dataset, table)
    phys_view_table: dict[str, tuple[str, str]] = {}
    for v_name, v_obj in all_views.items():
        if v_obj.derived_table is not None:
            continue
        tref = _parse_lookml_table_name(v_obj.sql_table_name, v_name)
        cand_key = ((tref.db or default_dataset).lower(), tref.name.lower())
        if cand_key in by_ds_tbl:
            phys_view_table[v_name] = cand_key
    for _ in range(3):
        for v_name, v_obj in all_views.items():
            if v_name in phys_view_table or v_obj.derived_table is not None:
                continue
            for ext in v_obj.extends or []:
                if ext in phys_view_table:
                    phys_view_table[v_name] = phys_view_table[ext]
                    break

    view_req_grants: dict[str, set[str]] = {}
    dim_req_grants: dict[tuple[str, str], set[str]] = {}
    dg_req_grants: dict[tuple[str, str], set[str]] = {}
    meas_req_grants: dict[tuple[str, str], set[str]] = {}
    dim_sql_override: dict[tuple[str, str], tuple[str, list[str]]] = {}
    view_rls_dims: dict[str, list[tuple[tuple[str, str], str]]] = {}  # view -> [(tbl_key, lkml_dim)]

    # Pass 1: Physical & extended views
    for v_name, v_obj in sorted(all_views.items()):
        tkey = phys_view_table.get(v_name)
        if not tkey:
            continue
        tsec = by_ds_tbl[tkey]
        if tkey in table_grants:
            view_req_grants.setdefault(v_name, set()).add(table_grants[tkey])

        rplan = rls_plans[tkey]
        if rplan.bq_col and rplan.bq_col in tsec.columns:
            m_fields = _match_view_field_for_bq_col(
                v_obj, tsec.columns[rplan.bq_col]
            )
            if m_fields:
                fk, fn, _ = m_fields[0]
                view_rls_dims[v_name] = [
                    (tkey, f"{fn}_raw" if fk == "dimension_group" else fn)
                ]

        for col_low, csec in sorted(tsec.columns.items()):
            if not csec.policy_tag:
                continue
            unmasked_g = col_unmasked_grants[(*tkey, col_low)]
            rom_g = col_read_or_mask_grants.get((*tkey, col_low))
            matched = _match_view_field_for_bq_col(v_obj, csec)
            for f_kind, f_name, orig_sql in matched:
                if f_kind == "dimension" and csec.mask_expression and rom_g:
                    dim_req_grants.setdefault((v_name, f_name), set()).add(rom_g)
                    masked_sql = _bq_mask_sql(
                        orig_sql, csec.bq_type, csec.mask_expression
                    )
                    liquid_sql = (
                        f"{{% if _user_attributes['{unmasked_g}'] == 'yes' %}}"
                        f"{orig_sql}{{% else %}}{masked_sql}{{% endif %}}"
                    )
                    dim_sql_override[(v_name, f_name)] = (liquid_sql, ["bq_masked"])
                elif f_kind == "dimension":
                    dim_req_grants.setdefault((v_name, f_name), set()).add(unmasked_g)
                else:
                    dg_req_grants.setdefault((v_name, f_name), set()).add(unmasked_g)

    # Pass 2: Multi-table Persisted & Ephemeral Derived Tables (SQL PDTs & Native Derived Tables)
    for v_name, v_obj in sorted(all_views.items()):
        dt = v_obj.derived_table
        if not dt:
            continue
        dt_sql = dt.get("sql") if isinstance(dt, dict) else dt.sql
        dt_es = dt.get("explore_source") if isinstance(dt, dict) else dt.explore_source

        if isinstance(dt_sql, str) and dt_sql.strip():
            spine_tbls, left_tbls, col_lineage = _analyze_sql_dt_tables(
                dt_sql, default_dataset, phys_view_table
            )
            _apply_dt_security(
                v_name=v_name,
                v_obj=v_obj,
                spine_tbls=spine_tbls & set(by_ds_tbl),
                left_tbls=left_tbls & set(by_ds_tbl),
                col_lineage=col_lineage,
                by_ds_tbl=by_ds_tbl,
                rls_plans=rls_plans,
                table_grants=table_grants,
                col_unmasked_grants=col_unmasked_grants,
                col_read_or_mask_grants=col_read_or_mask_grants,
                view_req_grants=view_req_grants,
                dim_req_grants=dim_req_grants,
                dg_req_grants=dg_req_grants,
                dim_sql_override=dim_sql_override,
                view_rls_dims=view_rls_dims,
                attrs=attrs,
                grants=grants,
                warnings=warnings,
            )
        elif dt_es:
            _apply_ndt_security(
                v_name=v_name,
                v_obj=v_obj,
                dt_es=dt_es,
                assembled_models=assembled_models,
                exp_base=exp_base,
                exp_ref=exp_ref,
                all_views=all_views,
                phys_view_table=phys_view_table,
                by_ds_tbl=by_ds_tbl,
                rls_plans=rls_plans,
                table_grants=table_grants,
                col_unmasked_grants=col_unmasked_grants,
                col_read_or_mask_grants=col_read_or_mask_grants,
                view_req_grants=view_req_grants,
                dim_req_grants=dim_req_grants,
                dg_req_grants=dg_req_grants,
                meas_req_grants=meas_req_grants,
                dim_sql_override=dim_sql_override,
                view_rls_dims=view_rls_dims,
                attrs=attrs,
                grants=grants,
                warnings=warnings,
            )

    # Pass 3: Transitive `${field}` grant propagation across dimensions & measures (e.g. `total_base_salary`)
    # ponytail: 4-pass fixed-point covers calculated field chains up to depth 4; upgrade to topological sort over `_extract_lookml_refs` if deeper chains appear.
    for _ in range(4):
        changed = False
        for v_name, v_obj in sorted(all_views.items()):
            for d_name, d_obj in (v_obj.dimension or {}).items():
                inh = _inherited_field_grants(
                    v_name,
                    d_obj.sql,
                    dim_req_grants,
                    dg_req_grants,
                    meas_req_grants,
                    dim_sql_override,
                    col_unmasked_for_masked=_unmasked_map_for_view(
                        v_name, v_obj, phys_view_table, by_ds_tbl, col_unmasked_grants
                    ),
                )
                cur = dim_req_grants.setdefault((v_name, d_name), set())
                if not inh.issubset(cur):
                    cur |= inh
                    changed = True
            for m_name, m_obj in (v_obj.measure or {}).items():
                inh = _inherited_field_grants(
                    v_name,
                    m_obj.sql,
                    dim_req_grants,
                    dg_req_grants,
                    meas_req_grants,
                    dim_sql_override,
                    col_unmasked_for_masked=_unmasked_map_for_view(
                        v_name, v_obj, phys_view_table, by_ds_tbl, col_unmasked_grants
                    ),
                    promote_masked_to_unmasked=True,
                )
                cur = meas_req_grants.setdefault((v_name, m_name), set())
                if not inh.issubset(cur):
                    cur |= inh
                    changed = True
        if not changed:
            break

    # Pass 4: Compile Explore, Join & Aggregate Table refinements
    explore_blocks = _compile_explore_refinements(
        assembled_models=assembled_models,
        model_filter=model_name,
        exp_base=exp_base,
        exp_ref=exp_ref,
        all_views=all_views,
        phys_view_table=phys_view_table,
        rls_plans=rls_plans,
        view_req_grants=view_req_grants,
        view_rls_dims=view_rls_dims,
        dim_sql_override=dim_sql_override,
        warnings=warnings,
    )

    out_files: dict[str, str] = {}
    if grants:
        ag_lines = [SECURITY_HEADER]
        for g_name, a_name in sorted(grants.items()):
            ag_lines.append(
                f"access_grant: {g_name} {{\n"
                f"  user_attribute: {a_name}\n"
                f'  allowed_values: ["yes"]\n'
                f"}}\n"
            )
        out_files["security/bq_access_grants.refinement.lkml"] = "\n".join(ag_lines)

    view_blocks = _render_view_refinements(
        all_views=all_views,
        view_req_grants=view_req_grants,
        dim_req_grants=dim_req_grants,
        dg_req_grants=dg_req_grants,
        meas_req_grants=meas_req_grants,
        dim_sql_override=dim_sql_override,
    )
    if view_blocks:
        out_files["security/views.refinement.lkml"] = (
            SECURITY_HEADER + "\n" + "\n\n".join(view_blocks) + "\n"
        )

    if explore_blocks:
        out_files["security/explores.refinement.lkml"] = (
            SECURITY_HEADER + "\n" + "\n\n".join(explore_blocks) + "\n"
        )

    return CompiledSecurityBundle(
        files=out_files,
        attributes=attrs,
        warnings=warnings,
    )


def _parse_virtual_project(files: dict[str, str]) -> LookmlProject:
    # ponytail: writes in-memory LookML map to a temp dir (~20ms) so `parse_lookml` reuses `lookml-parser` glob/modelAssembly; upgrade path is adding `files: dict[str, str]` directly to `parse_lookml`.
    import tempfile

    with tempfile.TemporaryDirectory(prefix="lkr_bq_sec_") as tmpdir:
        root = Path(tmpdir)
        for rel_path, content in files.items():
            p = root / rel_path
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content, encoding="utf-8")
        return parse_lookml(path=root).apply_defaults()


def _unmasked_map_for_view(
    v_name: str,
    v_obj: LookmlView,
    phys_view_table: dict[str, tuple[str, str]],
    by_ds_tbl: dict[tuple[str, str], BqTableSecurity],
    col_unmasked_grants: dict[tuple[str, str, str], str],
) -> dict[str, str]:
    out: dict[str, str] = {}
    tkey = phys_view_table.get(v_name)
    if not tkey:
        return out
    tsec = by_ds_tbl[tkey]
    for col_low, csec in tsec.columns.items():
        ug = col_unmasked_grants.get((*tkey, col_low))
        if ug and csec.mask_expression:
            for fk, fn, _ in _match_view_field_for_bq_col(v_obj, csec):
                if fk == "dimension":
                    out[fn] = ug
    return out


def _inherited_field_grants(
    default_view: str,
    sql: str | None,
    dim_req_grants: dict[tuple[str, str], set[str]],
    dg_req_grants: dict[tuple[str, str], set[str]],
    meas_req_grants: dict[tuple[str, str], set[str]],
    dim_sql_override: dict[tuple[str, str], tuple[str, list[str]]],
    col_unmasked_for_masked: dict[str, str],
    *,
    promote_masked_to_unmasked: bool = False,
) -> set[str]:
    out: set[str] = set()
    for ref in _extract_lookml_refs(sql):
        rv, rf = ref.split(".", 1) if "." in ref else (default_view, ref)
        out |= dim_req_grants.get((rv, rf), set())
        out |= meas_req_grants.get((rv, rf), set())
        if promote_masked_to_unmasked and (rv, rf) in dim_sql_override and rv == default_view:
            ug = col_unmasked_for_masked.get(rf)
            if ug:
                out.add(ug)
        for (gv, gname), gset in dg_req_grants.items():
            if gv == rv and (rf == gname or rf.startswith(f"{gname}_")):
                out |= gset
    return out


def _apply_dt_security(
    *,
    v_name: str,
    v_obj: LookmlView,
    spine_tbls: set[tuple[str, str]],
    left_tbls: set[tuple[str, str]],
    col_lineage: dict[str, list[tuple[tuple[str, str], str, bool]]],
    by_ds_tbl: dict[tuple[str, str], BqTableSecurity],
    rls_plans: dict[tuple[str, str], _TableRlsPlan],
    table_grants: dict[tuple[str, str], str],
    col_unmasked_grants: dict[tuple[str, str, str], str],
    col_read_or_mask_grants: dict[tuple[str, str, str], str],
    view_req_grants: dict[str, set[str]],
    dim_req_grants: dict[tuple[str, str], set[str]],
    dg_req_grants: dict[tuple[str, str], set[str]],
    dim_sql_override: dict[tuple[str, str], tuple[str, list[str]]],
    view_rls_dims: dict[str, list[tuple[tuple[str, str], str]]],
    attrs: dict[str, DesiredAttributeSpec],
    grants: dict[str, str],
    warnings: list[str],
) -> None:
    # 1. Spine table IAM grants apply to the whole PDT view
    for st in sorted(spine_tbls):
        if st in table_grants:
            view_req_grants.setdefault(v_name, set()).add(table_grants[st])

    # Build map of (source_table, source_col) -> PDT output dimension name
    src_col_to_pdt_dim: dict[tuple[tuple[str, str], str], str] = {}
    for d_name, d_obj in (v_obj.dimension or {}).items():
        for out_col, origins in col_lineage.items():
            if _field_matches_column(out_col, d_name, d_obj.sql, "dimension"):
                for st, sc, is_direct in origins:
                    if is_direct:
                        src_col_to_pdt_dim[(st, sc)] = d_name

    # 2. Spine RAP -> map to PDT output dimension (or fail-closed to full_bypass_grant / deny_grant if aggregated away!)
    for st in sorted(spine_tbls):
        rplan = rls_plans.get(st)
        if not rplan or rplan.mode == "none":
            continue
        pdt_dim = (
            src_col_to_pdt_dim.get((st, rplan.bq_col)) if rplan.bq_col else None
        )
        if pdt_dim and rplan.mode == "access_filter":
            view_rls_dims.setdefault(v_name, []).append((st, pdt_dim))
        elif rplan.full_bypass_grant:
            view_req_grants.setdefault(v_name, set()).add(rplan.full_bypass_grant)
            warnings.append(
                f"Derived table '{v_name}' omits RAP column '{rplan.bq_col}' from '{st[0]}.{st[1]}'; "
                f"restricted to full-table RAP grant '{rplan.full_bypass_grant}'."
            )
        else:
            deny_grant = _slug(f"bq_rls_missing_{st[0]}_{st[1]}_{v_name}")
            _register_bool_grant(deny_grant, deny_grant, BqPrincipals(), attrs, grants)
            view_req_grants.setdefault(v_name, set()).add(deny_grant)
            warnings.append(
                f"Derived table '{v_name}' aggregates row-secured table '{st[0]}.{st[1]}' without exposing "
                f"RAP column '{rplan.bq_col}'; add '{rplan.bq_col}' to SELECT to enable partial-RAP access."
            )

    # 3. Column-level policy tags, masking, and LEFT JOIN table IAM / RAP scoping!
    for f_kind, f_dict in (
        ("dimension", v_obj.dimension or {}),
        ("dimension_group", v_obj.dimension_group or {}),
    ):
        for f_name, f_obj in sorted(f_dict.items()):
            matched_origins: list[tuple[tuple[str, str], str, bool]] = []
            for out_col, origins in col_lineage.items():
                if _field_matches_column(
                    out_col,
                    f_name,
                    f_obj.sql,
                    f_kind,
                    list(getattr(f_obj, "timeframes", None) or []),
                ):
                    matched_origins.extend(origins)

            target_grants = (
                dim_req_grants.setdefault((v_name, f_name), set())
                if f_kind == "dimension"
                else dg_req_grants.setdefault((v_name, f_name), set())
            )
            orig_sql = (f_obj.sql or f"${{TABLE}}.{f_name}").strip()
            cur_sql = orig_sql
            cur_tags: list[str] = []

            for st, sc, is_direct in matched_origins:
                if st not in by_ds_tbl:
                    continue
                # LEFT JOIN table IAM scopes strictly to columns originating from that LEFT JOIN table!
                if st in left_tbls and st in table_grants:
                    target_grants.add(table_grants[st])

                tsec = by_ds_tbl[st]
                csec = tsec.columns.get(sc)
                if csec and csec.policy_tag:
                    ug = col_unmasked_grants[(*st, sc)]
                    rom = col_read_or_mask_grants.get((*st, sc))
                    if (
                        f_kind == "dimension"
                        and is_direct
                        and csec.mask_expression
                        and rom
                    ):
                        target_grants.add(rom)
                        msql = _bq_mask_sql(
                            cur_sql, csec.bq_type, csec.mask_expression
                        )
                        cur_sql = (
                            f"{{% if _user_attributes['{ug}'] == 'yes' %}}"
                            f"{cur_sql}{{% else %}}{msql}{{% endif %}}"
                        )
                        cur_tags.append("bq_masked")
                    else:
                        target_grants.add(ug)

                # LEFT JOIN table RAP -> null out LEFT-joined column when RAP fails (matching BQ LEFT JOIN + RAP!)
                if st in left_tbls:
                    lrplan = rls_plans.get(st)
                    if lrplan and lrplan.mode != "none":
                        pdt_rap_dim = (
                            src_col_to_pdt_dim.get((st, lrplan.bq_col))
                            if lrplan.bq_col
                            else None
                        )
                        if f_kind == "dimension" and pdt_rap_dim and lrplan.sql_template:
                            guard = lrplan.sql_template.replace(
                                f"${{{{ALIAS}}.{lrplan.bq_col}}}",
                                f"${{{v_name}.{pdt_rap_dim}}}",
                            ).replace("{ALIAS}", v_name)
                            cur_sql = f"CASE WHEN {guard} THEN {cur_sql} ELSE NULL END"
                        elif lrplan.full_bypass_grant:
                            target_grants.add(lrplan.full_bypass_grant)
                        else:
                            deny_g = _slug(
                                f"bq_rls_missing_{st[0]}_{st[1]}_{v_name}_{f_name}"
                            )
                            _register_bool_grant(
                                deny_g, deny_g, BqPrincipals(), attrs, grants
                            )
                            target_grants.add(deny_g)

            if cur_sql != orig_sql and f_kind == "dimension":
                dim_sql_override[(v_name, f_name)] = (cur_sql, cur_tags)


def _apply_ndt_security(
    *,
    v_name: str,
    v_obj: LookmlView,
    dt_es: dict[str, LookmlExploreSource] | LookmlExploreSource,
    assembled_models: dict[str, LookmlModel],
    exp_base: dict[str, list[tuple[str, Any, dict[str, Any]]]],
    exp_ref: dict[str, list[tuple[str, Any, dict[str, Any]]]],
    all_views: dict[str, LookmlView],
    phys_view_table: dict[str, tuple[str, str]],
    by_ds_tbl: dict[tuple[str, str], BqTableSecurity],
    rls_plans: dict[tuple[str, str], _TableRlsPlan],
    table_grants: dict[tuple[str, str], str],
    col_unmasked_grants: dict[tuple[str, str, str], str],
    col_read_or_mask_grants: dict[tuple[str, str, str], str],
    view_req_grants: dict[str, set[str]],
    dim_req_grants: dict[tuple[str, str], set[str]],
    dg_req_grants: dict[tuple[str, str], set[str]],
    meas_req_grants: dict[tuple[str, str], set[str]],
    dim_sql_override: dict[tuple[str, str], tuple[str, list[str]]],
    view_rls_dims: dict[str, list[tuple[tuple[str, str], str]]],
    attrs: dict[str, DesiredAttributeSpec],
    grants: dict[str, str],
    warnings: list[str],
) -> None:
    if isinstance(dt_es, dict):
        if not dt_es:
            return
        src_exp_name, es_obj = next(iter(dt_es.items()))
    else:
        src_exp_name, es_obj = (dt_es.name_ or ""), dt_es
    if not src_exp_name:
        return

    target_model = next(
        (
            m
            for m in assembled_models.values()
            if src_exp_name in (m.explore or {})
        ),
        None,
    )
    if not target_model or not target_model.explore:
        return
    raw_exp = target_model.explore[src_exp_name]
    exp_obj = raw_exp[0] if isinstance(raw_exp, list) else raw_exp
    if not isinstance(exp_obj, LookmlExplore):
        return

    chain = _build_chain(src_exp_name, exp_base, exp_ref)
    jgraph = build_explore_join_graph(
        src_exp_name, exp_obj, chain, target_model.view or all_views
    )
    alias_to_view: dict[str, str] = {jgraph.base_alias: jgraph.base_view}
    spine_aliases: set[str] = {jgraph.base_alias, *jgraph.always_join}
    left_aliases: set[str] = set()
    for j_al, j_node in jgraph.joins.items():
        alias_to_view[j_al] = j_node.target_view
        if j_node.type == "left_outer" and not j_node.always_join:
            left_aliases.add(j_al)
        else:
            spine_aliases.add(j_al)

    # Promote any LEFT JOIN alias referenced in `filters:` or `expression_custom_filter:` to spine!
    if es_obj.expression_custom_filter:
        for ref in _extract_lookml_refs(es_obj.expression_custom_filter):
            al = ref.split(".", 1)[0] if "." in ref else jgraph.base_alias
            if al in left_aliases:
                left_aliases.remove(al)
                spine_aliases.add(al)
    for f_item in _as_list(es_obj.filters):
        if isinstance(f_item, dict):
            for k in f_item:
                al = str(k).split(".", 1)[0] if "." in str(k) else jgraph.base_alias
                if al in left_aliases:
                    left_aliases.remove(al)
                    spine_aliases.add(al)

    # 1. Spine table grants on whole NDT view
    for al in sorted(spine_aliases):
        sv = alias_to_view.get(al, al)
        view_req_grants.setdefault(v_name, set()).update(view_req_grants.get(sv, set()))

    # Map NDT `column:` entries -> (alias, src_view, src_field)
    ndt_col_origin: dict[str, tuple[str, str, str]] = {}
    for col_name, col_spec in (es_obj.column or {}).items():
        f_ref = (col_spec.field if col_spec and col_spec.field else col_name).strip()
        al, sf = f_ref.split(".", 1) if "." in f_ref else (jgraph.base_alias, f_ref)
        sv = alias_to_view.get(al, al)
        ndt_col_origin[col_name] = (al, sv, sf)

    # Track exposed RLS columns per alias
    exposed_rls_by_alias: dict[str, str] = {}
    for col_name, (al, sv, sf) in ndt_col_origin.items():
        sv_rls = view_rls_dims.get(sv) or []
        if any(rdim == sf for _, rdim in sv_rls) and col_name in (v_obj.dimension or {}):
            exposed_rls_by_alias[al] = col_name

    # 2. Spine RAP propagation to NDT
    for al in sorted(spine_aliases):
        sv = alias_to_view.get(al, al)
        tkey = phys_view_table.get(sv)
        if not tkey:
            continue
        rplan = rls_plans.get(tkey)
        if not rplan or rplan.mode == "none":
            continue
        if al in exposed_rls_by_alias and rplan.mode == "access_filter":
            view_rls_dims.setdefault(v_name, []).append(
                (tkey, exposed_rls_by_alias[al])
            )
        elif rplan.full_bypass_grant:
            view_req_grants.setdefault(v_name, set()).add(rplan.full_bypass_grant)
            warnings.append(
                f"Persisted/Native derived table '{v_name}' omits RAP field for '{al}'; "
                f"restricted to full-table RAP grant '{rplan.full_bypass_grant}'."
            )
        else:
            deny_grant = _slug(f"bq_rls_missing_{tkey[0]}_{tkey[1]}_{v_name}")
            _register_bool_grant(deny_grant, deny_grant, BqPrincipals(), attrs, grants)
            view_req_grants.setdefault(v_name, set()).add(deny_grant)
            warnings.append(
                f"Persisted/Native derived table '{v_name}' aggregates row-secured '{al}' without exposing "
                f"RAP field '{rplan.bq_col}'; include it in explore_source columns to enable partial-RAP access."
            )

    # 3. Column-scoped table IAM, policy tags, masking, and LEFT JOIN RAP on NDT columns!
    for col_name, (al, sv, sf) in sorted(ndt_col_origin.items()):
        tkey = phys_view_table.get(sv)
        inherited: set[str] = set()
        if al in left_aliases:
            inherited |= view_req_grants.get(sv, set())
        inherited |= dim_req_grants.get((sv, sf), set())
        inherited |= meas_req_grants.get((sv, sf), set())
        for (gv, gname), gset in dg_req_grants.items():
            if gv == sv and (sf == gname or sf.startswith(f"{gname}_")):
                inherited |= gset

        v_dims = v_obj.dimension or {}
        if col_name in v_dims:
            if inherited:
                dim_req_grants.setdefault((v_name, col_name), set()).update(inherited)
            orig_ndt_sql = (v_dims[col_name].sql or f"${{TABLE}}.{col_name}").strip()
            cur_sql = orig_ndt_sql
            cur_tags: list[str] = []
            if (sv, sf) in dim_sql_override:
                up_sql, up_tags = dim_sql_override[(sv, sf)]
                # Rewrite upstream `${TABLE}.<src_col>` masking expression to `${TABLE}.<ndt_col>`
                src_dim = (all_views.get(sv) or LookmlView()).dimension or {}
                raw_src_sql = src_dim[sf].sql if sf in src_dim else None
                src_sql = (raw_src_sql or f"${{TABLE}}.{sf}").strip()
                cur_sql = up_sql.replace(src_sql, cur_sql)
                cur_tags.extend(up_tags)
            if al in left_aliases and tkey:
                lrplan = rls_plans.get(tkey)
                if lrplan and lrplan.mode != "none":
                    ndt_rap_dim = exposed_rls_by_alias.get(al)
                    if ndt_rap_dim and lrplan.sql_template and lrplan.bq_col:
                        guard = lrplan.sql_template.replace(
                            f"${{{{ALIAS}}.{lrplan.bq_col}}}",
                            f"${{{v_name}.{ndt_rap_dim}}}",
                        ).replace("{ALIAS}", v_name)
                        cur_sql = f"CASE WHEN {guard} THEN {cur_sql} ELSE NULL END"
                    elif lrplan.full_bypass_grant:
                        dim_req_grants.setdefault((v_name, col_name), set()).add(
                            lrplan.full_bypass_grant
                        )
                    else:
                        deny_g = _slug(
                            f"bq_rls_missing_{tkey[0]}_{tkey[1]}_{v_name}_{col_name}"
                        )
                        _register_bool_grant(
                            deny_g, deny_g, BqPrincipals(), attrs, grants
                        )
                        dim_req_grants.setdefault((v_name, col_name), set()).add(deny_g)
            if cur_sql != orig_ndt_sql:
                dim_sql_override[(v_name, col_name)] = (cur_sql, cur_tags)
        elif col_name in (v_obj.dimension_group or {}):
            if al in left_aliases and tkey and rls_plans[tkey].mode != "none":
                lrplan = rls_plans[tkey]
                if lrplan.full_bypass_grant:
                    inherited.add(lrplan.full_bypass_grant)
                else:
                    deny_g = _slug(
                        f"bq_rls_missing_{tkey[0]}_{tkey[1]}_{v_name}_{col_name}"
                    )
                    _register_bool_grant(deny_g, deny_g, BqPrincipals(), attrs, grants)
                    inherited.add(deny_g)
            if inherited:
                dg_req_grants.setdefault((v_name, col_name), set()).update(inherited)


def _render_view_refinements(
    *,
    all_views: dict[str, LookmlView],
    view_req_grants: dict[str, set[str]],
    dim_req_grants: dict[tuple[str, str], set[str]],
    dg_req_grants: dict[tuple[str, str], set[str]],
    meas_req_grants: dict[tuple[str, str], set[str]],
    dim_sql_override: dict[tuple[str, str], tuple[str, list[str]]],
) -> list[str]:
    blocks: list[str] = []
    for v_name in sorted(all_views):
        v_obj = all_views[v_name]
        lines: list[str] = []
        vg = sorted(view_req_grants.get(v_name, set()))
        if vg:
            lines.append(f"  required_access_grants: [{', '.join(vg)}]")

        for d_name in sorted(v_obj.dimension or {}):
            dg = sorted(dim_req_grants.get((v_name, d_name), set()))
            sql_ov = dim_sql_override.get((v_name, d_name))
            if not dg and not sql_ov:
                continue
            d_lines = [f"  dimension: {d_name} {{"]
            if dg:
                d_lines.append(f"    required_access_grants: [{', '.join(dg)}]")
            if sql_ov:
                ov_sql, ov_tags = sql_ov
                if ov_tags:
                    existing_tags = list((v_obj.dimension or {})[d_name].tags or [])
                    merged_tags = list(dict.fromkeys([*existing_tags, *ov_tags]))
                    quoted_tags = ", ".join(json.dumps(t) for t in merged_tags)
                    d_lines.append(f"    tags: [{quoted_tags}]")
                d_lines.append(f"    sql: {ov_sql} ;;")
            d_lines.append("  }")
            lines.extend(d_lines)

        for dg_name in sorted(v_obj.dimension_group or {}):
            dgg = sorted(dg_req_grants.get((v_name, dg_name), set()))
            if not dgg:
                continue
            lines.append(
                f"  dimension_group: {dg_name} {{\n"
                f"    required_access_grants: [{', '.join(dgg)}]\n"
                f"  }}"
            )

        for m_name in sorted(v_obj.measure or {}):
            mg = sorted(meas_req_grants.get((v_name, m_name), set()))
            if not mg:
                continue
            lines.append(
                f"  measure: {m_name} {{\n"
                f"    required_access_grants: [{', '.join(mg)}]\n"
                f"  }}"
            )

        if lines:
            blocks.append(f"view: +{v_name} {{\n" + "\n".join(lines) + "\n}")
    return blocks


def _compile_explore_refinements(
    *,
    assembled_models: dict[str, LookmlModel],
    model_filter: str | None,
    exp_base: dict[str, list[tuple[str, Any, dict[str, Any]]]],
    exp_ref: dict[str, list[tuple[str, Any, dict[str, Any]]]],
    all_views: dict[str, LookmlView],
    phys_view_table: dict[str, tuple[str, str]],
    rls_plans: dict[tuple[str, str], _TableRlsPlan],
    view_req_grants: dict[str, set[str]],
    view_rls_dims: dict[str, list[tuple[tuple[str, str], str]]],
    dim_sql_override: dict[tuple[str, str], tuple[str, list[str]]],
    warnings: list[str],
) -> list[str]:
    blocks: list[str] = []
    seen_explores: set[str] = set()

    for m_name, m_obj in sorted(assembled_models.items()):
        if model_filter and m_name != model_filter:
            continue
        for exp_name, raw_exp in sorted((m_obj.explore or {}).items()):
            if exp_name in seen_explores:
                continue
            exp_obj = raw_exp[0] if isinstance(raw_exp, list) else raw_exp
            if not isinstance(exp_obj, LookmlExplore):
                continue
            seen_explores.add(exp_name)

            chain = _build_chain(exp_name, exp_base, exp_ref)
            jgraph = build_explore_join_graph(
                exp_name, exp_obj, chain, m_obj.view or all_views, model_name=m_name
            )

            exp_grants: set[str] = set(exp_obj.required_access_grants or [])
            exp_grants |= view_req_grants.get(jgraph.base_view, set())

            access_filters: list[tuple[str, str]] = []
            sql_where_clauses: list[str] = []
            if exp_obj.sql_always_where:
                sql_where_clauses.append(f"({exp_obj.sql_always_where.strip()})")

            def _add_explore_level_rls(
                alias: str,
                view_name: str,
                af_out: list[tuple[str, str]],
                where_out: list[str],
            ) -> None:
                handled_af = False
                for tkey, lkml_dim in view_rls_dims.get(view_name, []):
                    rplan = rls_plans[tkey]
                    if rplan.mode == "access_filter" and rplan.user_attribute:
                        af_out.append(
                            (f"{alias}.{lkml_dim}", rplan.user_attribute)
                        )
                        handled_af = True
                if handled_af:
                    return
                tkey = phys_view_table.get(view_name)
                if tkey and rls_plans[tkey].mode != "none":
                    rplan = rls_plans[tkey]
                    if rplan.sql_template:
                        where_out.append(
                            rplan.sql_template.replace("{ALIAS}", alias)
                        )

            _add_explore_level_rls(
                jgraph.base_alias, jgraph.base_view, access_filters, sql_where_clauses
            )

            join_lines: list[str] = []
            for j_alias, j_node in sorted(jgraph.joins.items()):
                tv = j_node.target_view
                jg = sorted(view_req_grants.get(tv, set()))
                is_inner = j_node.type != "left_outer" or j_node.always_join
                if is_inner:
                    exp_grants |= set(jg)
                    _add_explore_level_rls(
                        j_alias, tv, access_filters, sql_where_clauses
                    )
                    if jg:
                        join_lines.append(
                            f"  join: {j_alias} {{\n"
                            f"    required_access_grants: [{', '.join(jg)}]\n"
                            f"  }}"
                        )
                else:
                    # `left_outer` join -> push RLS into `sql_on:` so join pruning & base `aggregate_table`s stay fast!
                    rls_clauses: list[str] = []
                    tv_rls_entries = view_rls_dims.get(tv) or (
                        [(phys_view_table[tv], "")]
                        if tv in phys_view_table
                        else []
                    )
                    for tkey, rdim in tv_rls_entries:
                        rplan = rls_plans[tkey]
                        if rplan.mode == "none":
                            continue
                        if rplan.uses_session_user_only and rdim:
                            rls_clauses.append(
                                f"${{{j_alias}.{rdim}}} = '{{{{ _user_attributes[\"email\"] }}}}'"
                            )
                        elif rplan.sql_template:
                            tpl = rplan.sql_template
                            if rdim and rplan.bq_col:
                                tpl = tpl.replace(
                                    f"${{{{ALIAS}}.{rplan.bq_col}}}",
                                    f"${{{j_alias}.{rdim}}}",
                                )
                            rls_clauses.append(tpl.replace("{ALIAS}", j_alias))
                    rls_guard = " AND ".join(rls_clauses) if rls_clauses else None

                    if jg or rls_guard:
                        j_sub = [f"  join: {j_alias} {{"]
                        if jg:
                            j_sub.append(
                                f"    required_access_grants: [{', '.join(jg)}]"
                            )
                        if rls_guard:
                            base_on = j_node.sql_on
                            if not base_on and j_node.equi_joins:
                                (lv, lc), (rv, rc) = j_node.equi_joins[0]
                                base_on = f"${{{lv}.{lc}}} = ${{{rv}.{rc}}}"
                            combined_on = (
                                f"({base_on.strip()}) AND ({rls_guard})"
                                if base_on
                                else rls_guard
                            )
                            j_sub.append(f"    sql_on: {combined_on} ;;")
                        j_sub.append("  }")
                        join_lines.extend(j_sub)

            # Ensure existing `aggregate_table:` blocks include Explore-level `access_filter` dimensions!
            agg_lines: list[str] = []
            af_dims = [f for f, _ in access_filters]
            if af_dims and exp_obj.aggregate_table:
                for agg_name, agg_obj in sorted(exp_obj.aggregate_table.items()):
                    q_raw = agg_obj.query
                    q_dict = (
                        next((x for x in q_raw if isinstance(x, dict)), {})
                        if isinstance(q_raw, list)
                        else q_raw
                        if isinstance(q_raw, dict)
                        else {}
                    )
                    cur_dims = [
                        _qualify_field_ref(str(d), jgraph.base_alias)
                        for d in (q_dict.get("dimensions") or [])
                    ]
                    for d in cur_dims:
                        dv, df = d.split(".", 1)
                        real_v = (
                            jgraph.base_view
                            if dv == jgraph.base_alias
                            else jgraph.joins[dv].target_view
                            if dv in jgraph.joins
                            else dv
                        )
                        if (real_v, df) in dim_sql_override:
                            warnings.append(
                                f"Aggregate table '{exp_name}.{agg_name}' groups by masked dimension '{d}', "
                                "which contains per-user Liquid and disables Aggregate Awareness."
                            )
                    missing = [d for d in af_dims if d not in cur_dims]
                    if missing:
                        merged = [*cur_dims, *missing]
                        agg_lines.append(
                            f"  aggregate_table: {agg_name} {{\n"
                            f"    query: {{\n"
                            f"      dimensions: [{', '.join(merged)}]\n"
                            f"    }}\n"
                            f"  }}"
                        )

            new_grants = sorted(exp_grants - set(exp_obj.required_access_grants or []))
            has_new_where = len(sql_where_clauses) > (
                1 if exp_obj.sql_always_where else 0
            )
            if (
                not new_grants
                and not access_filters
                and not has_new_where
                and not join_lines
                and not agg_lines
            ):
                continue

            e_lines = [f"explore: +{exp_name} {{"]
            if exp_grants:
                e_lines.append(
                    f"  required_access_grants: [{', '.join(sorted(exp_grants))}]"
                )
            for af_field, af_attr in dict.fromkeys(access_filters):
                e_lines.append(
                    f"  access_filter: {{\n"
                    f"    field: {af_field}\n"
                    f"    user_attribute: {af_attr}\n"
                    f"  }}"
                )
            if has_new_where:
                e_lines.append(
                    f"  sql_always_where: {' AND '.join(sql_where_clauses)} ;;"
                )
            e_lines.extend(join_lines)
            e_lines.extend(agg_lines)
            e_lines.append("}")
            blocks.append("\n".join(e_lines))

    return blocks


def ensure_model_security_includes(model_content: str, security_files: list[str]) -> str:
    """Idempotently add or remove `include: "/security/..."` lines at the bottom of `.model.lkml`."""
    cleaned = re.sub(
        r'\n?# BEGIN LKR BQ SECURITY\n.*?# END LKR BQ SECURITY\n?',
        "\n",
        model_content,
        flags=re.DOTALL,
    ).rstrip()
    if not security_files:
        return cleaned + "\n"
    inc_lines = [f'include: "/{p}"' for p in sorted(security_files)]
    block = (
        "\n\n# BEGIN LKR BQ SECURITY\n"
        + "\n".join(inc_lines)
        + "\n# END LKR BQ SECURITY\n"
    )
    return cleaned + block


def sync_looker_security_attributes(
    sdk: Any,
    project_id: str,
    desired: dict[str, DesiredAttributeSpec],
) -> dict[str, Any]:
    """Reconcile Looker User Attributes, Groups, and Multi-Group RAP Unions via `UserAttributeUpdater`."""
    state_key = _slug(f"state_{project_id}")
    prev_state: dict[str, dict[str, Any]] = {}
    try:
        arts = sdk.artifact(namespace=SECURITY_ARTIFACT_NAMESPACE, key=state_key)
        item = arts[0] if isinstance(arts, list) and arts else arts
        raw_val = getattr(item, "value", None) or (
            item.get("value") if isinstance(item, dict) else None
        )
        if isinstance(raw_val, str) and raw_val.strip():
            prev_state = json.loads(raw_val)
    except Exception:  # noqa: BLE001
        prev_state = {}

    # Resolve group names -> Looker group names (matching either `foo@domain.com` or short `foo`)
    existing_groups: dict[str, str] = {}
    try:
        for g in sdk.all_groups(fields="id,name") or []:
            gname = getattr(g, "name", None)
            gid = getattr(g, "id", None)
            if gname and gid:
                existing_groups[str(gname).lower()] = str(gname)
    except Exception as e:  # noqa: BLE001
        logger.debug(f"Could not list Looker groups: {e}")

    def _resolve_looker_group_name(bq_group: str) -> str:
        low = bq_group.lower()
        return existing_groups.get(low) or existing_groups.get(
            low.split("@", 1)[0], bq_group
        )

    created_or_updated: list[str] = []
    deleted_attrs: list[str] = []
    next_state: dict[str, dict[str, Any]] = {}

    # 1. Delete attributes whose BQ policies were completely removed
    for old_attr in sorted(set(prev_state) - set(desired)):
        try:
            UserAttributeUpdater(
                user_attribute=old_attr,
                update_type="default",
            ).delete_attribute(sdk=sdk)
            deleted_attrs.append(old_attr)
        except Exception as e:  # noqa: BLE001
            logger.debug(f"Attribute cleanup notice for '{old_attr}': {e}")

    # 2. Upsert current attributes & reconcile group/user bindings + multi-group RAP unions
    for attr_name, spec in sorted(desired.items()):
        resolved_groups = {
            _resolve_looker_group_name(g): val for g, val in spec.groups.items()
        }
        resolved_users = dict(spec.users)

        # Multi-group RAP union: if a Looker user belongs to >=2 RAP groups, union their filter values!
        # ponytail: O(G) `all_group_users` calls per multi-group RAP attribute at sync time; if dynamic SAML/OIDC group churn happens between syncs, upgrade path is emitting per-policy boolean grants in `sql_always_where`.
        if spec.attr_type in ("advanced_filter_string", "advanced_filter_number") and len(
            resolved_groups
        ) >= 2:
            wildcard_tokens = {"%,NULL", "%", "NULL, (-inf, inf)"}
            user_group_vals: dict[str, list[str]] = {}
            for gname, gval in resolved_groups.items():
                try:
                    found = sdk.search_groups(name=gname, fields="id")
                    group_id = getattr(found[0], "id", None) if found else None
                    if not group_id:
                        continue
                    for u in sdk.all_group_users(group_id=str(group_id), fields="email") or []:
                        u_email = getattr(u, "email", None)
                        if u_email:
                            user_group_vals.setdefault(str(u_email), []).append(gval)
                except Exception as e:  # noqa: BLE001
                    logger.debug(f"Group user lookup notice for '{gname}': {e}")
            for u_email, gvals in user_group_vals.items():
                if len(gvals) >= 2 and u_email not in resolved_users:
                    if any(v in wildcard_tokens for v in gvals):
                        resolved_users[u_email] = next(
                            v for v in gvals if v in wildcard_tokens
                        )
                    else:
                        parts = [
                            tok.strip()
                            for gv in gvals
                            for tok in gv.split(",")
                            if tok.strip()
                        ]
                        resolved_users[u_email] = ",".join(dict.fromkeys(parts))

        updater = UserAttributeUpdater(
            user_attribute=attr_name,
            update_type="default",
            value=spec.default_value,
        )
        attr_id = updater.ensure_attribute(
            sdk=sdk,
            default_value=spec.default_value,
            attr_type=spec.attr_type,
        )
        created_or_updated.append(attr_name)

        old_entry = prev_state.get(attr_name) or {}
        old_groups: dict[str, str] = old_entry.get("groups") or {}
        old_users: dict[str, str] = old_entry.get("users") or {}

        for stale_g in sorted(set(old_groups) - set(resolved_groups)):
            try:
                UserAttributeUpdater(
                    user_attribute=attr_name,
                    user_attribute_id=attr_id,
                    update_type="group",
                    group_name=stale_g,
                ).delete_user_attribute_value(sdk=sdk)
            except Exception as e:  # noqa: BLE001
                logger.debug(f"Stale group binding delete notice ({attr_name}/{stale_g}): {e}")

        for stale_u in sorted(set(old_users) - set(resolved_users)):
            try:
                UserAttributeUpdater(
                    user_attribute=attr_name,
                    user_attribute_id=attr_id,
                    update_type="user",
                    email=stale_u,
                ).delete_user_attribute_value(sdk=sdk)
            except Exception as e:  # noqa: BLE001
                logger.debug(f"Stale user binding delete notice ({attr_name}/{stale_u}): {e}")

        for gname, gval in sorted(resolved_groups.items()):
            UserAttributeUpdater(
                user_attribute=attr_name,
                user_attribute_id=attr_id,
                update_type="group",
                group_name=gname,
                value=gval,
            ).update_user_attribute_value(sdk=sdk, create_group_if_missing=True)

        for u_email, uval in sorted(resolved_users.items()):
            try:
                UserAttributeUpdater(
                    user_attribute=attr_name,
                    user_attribute_id=attr_id,
                    update_type="user",
                    email=u_email,
                    value=uval,
                ).update_user_attribute_value(sdk=sdk)
            except ValueError:
                # Looker user account may not exist yet for every BQ user email; skip without failing group sync
                logger.debug(f"Skipping non-existent Looker user '{u_email}' for '{attr_name}'")

        next_state[attr_name] = {
            "attr_type": spec.attr_type,
            "default_value": spec.default_value,
            "groups": resolved_groups,
            "users": resolved_users,
        }

    try:
        sdk.update_artifacts(
            namespace=SECURITY_ARTIFACT_NAMESPACE,
            body=[
                models40.UpdateArtifact(
                    key=state_key,
                    value=json.dumps(next_state),
                    content_type="application/json",
                )
            ],
        )
    except Exception as e:  # noqa: BLE001
        logger.debug(f"Security artifact state save notice: {e}")

    return {
        "synced_attributes": created_or_updated,
        "deleted_attributes": deleted_attrs,
    }
