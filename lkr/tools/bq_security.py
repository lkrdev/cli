class BqPermissionDeniedError(RuntimeError):
    """Raised when GCP denies an ACL discovery API call (fail-closed)."""

    def __init__(
        self,
        *,
        endpoint: str,
        status_code: int,
        permission: str | None,
        resource: str | None,
        raw_message: str,
    ) -> None:
        self.endpoint = endpoint
        self.status_code = status_code
        self.permission = permission
        self.resource = resource
        hint = (
            f" Missing GCP IAM permission: '{permission}'."
            if permission
            else ""
        )
        super().__init__(
            f"BigQuery security discovery failed closed ({status_code}) on {endpoint}:{hint} {raw_message}"
        )


@dataclass
class BqPrincipals:
    groups: set[str] = field(default_factory=set)
    users: set[str] = field(default_factory=set)
    public: bool = False  # allUsers / allAuthenticatedUsers / domain-wide

    def is_empty(self) -> bool:
        return not self.groups and not self.users and not self.public

    def union(self, other: "BqPrincipals") -> "BqPrincipals":
        return BqPrincipals(
            groups=self.groups | other.groups,
            users=self.users | other.users,
            public=self.public or other.public,
        )


