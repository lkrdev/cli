"""BigQuery table change listener and LookML view auto-upserter.

Inspects BigQuery table schema changes, checks existing LookML view files
for the autogenerated header guard, safely upserts fields while protecting
human-written definitions, records sync artifacts, and creates GitHub PRs.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import time
from pathlib import Path
from typing import Any

from lkr.logger import structured_logger as logger

AUTOGENERATED_HEADER = "# AUTOGENERATED BY LKR - DO NOT EDIT MANUALLY"
AUTOGENERATED_PREFIX = "# AUTOGENERATED"


def is_autogenerated_view(content: str) -> bool:
    """Return True if the LookML view content has an autogenerated header guard."""
    trimmed = content.lstrip()
    return AUTOGENERATED_HEADER in content[:300] or trimmed.startswith(
        AUTOGENERATED_PREFIX
    )


def bq_type_to_lookml(bq_type: str) -> tuple[str, str]:
    """Map BigQuery data type to (lookml_field_kind, lookml_type).

    Field kind is 'dimension' or 'dimension_group'.
    """
    clean_type = bq_type.upper().split("(")[0].strip()
    if clean_type in ("TIMESTAMP", "DATETIME", "DATE", "TIME"):
        return ("dimension_group", "time")
    if clean_type in (
        "INT64",
        "INTEGER",
        "INT",
        "SMALLINT",
        "BIGINT",
        "TINYINT",
        "BYTEINT",
        "NUMERIC",
        "BIGNUMERIC",
        "DECIMAL",
        "BIGDECIMAL",
        "FLOAT64",
        "FLOAT",
    ):
        return ("dimension", "number")
    if clean_type in ("BOOL", "BOOLEAN"):
        return ("dimension", "yesno")
    return ("dimension", "string")


def generate_dimension_snippet(
    col_name: str,
    bq_type: str,
    description: str | None = None,
) -> str:
    """Generate LookML dimension or dimension_group string for a single column."""
    kind, lkml_type = bq_type_to_lookml(bq_type)
    desc_str = f'    description: "{description}"\n' if description else ""

    if kind == "dimension_group":
        return (
            f"  dimension_group: {col_name} {{\n"
            f"    type: time\n"
            f"    timeframes: [raw, time, date, week, month, quarter, year]\n"
            f"{desc_str}"
            f"    sql: ${{TABLE}}.{col_name} ;;\n"
            f"  }}\n"
        )
    return (
        f"  dimension: {col_name} {{\n"
        f"    type: {lkml_type}\n"
        f"{desc_str}"
        f"    sql: ${{TABLE}}.{col_name} ;;\n"
        f"  }}\n"
    )


def generate_full_view(
    project: str,
    dataset: str,
    table_name: str,
    columns: list[dict[str, Any]],
    sql_table_name: str | None = None,
) -> str:
    """Generate a complete autogenerated LookML view file with header guard."""
    resolved_sql_table = sql_table_name or f"`{project}.{dataset}.{table_name}`"
    lines = [
        AUTOGENERATED_HEADER,
        f"# Auto-synchronized from BigQuery table: {project}.{dataset}.{table_name}",
        "",
        f"view: {table_name} {{",
        f"  sql_table_name: {resolved_sql_table} ;;",
        "",
    ]
    for col in columns:
        lines.append(
            generate_dimension_snippet(
                col["name"],
                col.get("type", "STRING"),
                col.get("description"),
            )
        )
    lines.append("}\n")
    return "\n".join(lines)


def find_view_file(lookml_dir: str | Path, table_name: str) -> Path | None:
    """Find an existing view file for table_name under lookml_dir."""
    lookml_path = Path(lookml_dir)
    target_filename = f"{table_name}.view.lkml"

    # Quick check in standard locations first
    candidates = [
        lookml_path / target_filename,
        lookml_path / "views" / target_filename,
    ]
    for c in candidates:
        if c.is_file():
            return c

    # Walk directory to find nested files
    for root, _, files in os.walk(lookml_path):
        if target_filename in files:
            return Path(root) / target_filename
    return None


def extract_defined_fields(content: str) -> set[str]:
    """Extract dimension, dimension_group, and measure names defined in a LookML view."""
    return set(
        re.findall(
            r"(?:dimension|dimension_group|measure):\s*([a-zA-Z0-9_]+)",
            content,
        )
    )


def upsert_view_file(
    lookml_dir: str | Path,
    project: str,
    dataset: str,
    table_name: str,
    columns: list[dict[str, Any]],
) -> tuple[bool, str, str]:
    """Upsert LookML view file for table_name based on BigQuery columns.

    Returns:
        (changed: bool, file_path: str, action: str)
        Actions: 'created', 'updated_autogenerated', 'appended_human_view', 'unchanged'
    """
    lookml_path = Path(lookml_dir)
    existing_file = find_view_file(lookml_path, table_name)

    if not existing_file:
        # File does not exist: create new autogenerated view
        views_dir = lookml_path / "views"
        target_dir = views_dir if views_dir.is_dir() else lookml_path
        target_dir.mkdir(parents=True, exist_ok=True)
        target_file = target_dir / f"{table_name}.view.lkml"

        view_content = generate_full_view(
            project=project,
            dataset=dataset,
            table_name=table_name,
            columns=columns,
        )
        target_file.write_text(view_content, encoding="utf-8")
        return (True, str(target_file), "created")

    current_content = existing_file.read_text(encoding="utf-8")

    if is_autogenerated_view(current_content):
        # File has header guard: safe to re-generate/upsert all fields
        # Preserve custom sql_table_name if user customized it
        sql_match = re.search(r"sql_table_name:\s*([^;]+);;", current_content)
        custom_sql = sql_match.group(1).strip() if sql_match else None

        updated_content = generate_full_view(
            project=project,
            dataset=dataset,
            table_name=table_name,
            columns=columns,
            sql_table_name=custom_sql,
        )

        if updated_content != current_content:
            existing_file.write_text(updated_content, encoding="utf-8")
            return (True, str(existing_file), "updated_autogenerated")
        return (False, str(existing_file), "unchanged")

    # Header guard is absent: protect human-written views by preserving custom definitions
    existing_fields = extract_defined_fields(current_content)
    new_cols = [col for col in columns if col["name"] not in existing_fields]

    if not new_cols:
        return (False, str(existing_file), "unchanged")

    # Append dimensions for only new columns before the last closing brace
    last_brace_index = current_content.rfind("}")
    if last_brace_index == -1:
        # Malformed view file, fallback to appending at end
        last_brace_index = len(current_content)

    new_snippets = [
        "\n  # Auto-added by LKR for new BigQuery columns",
    ]
    for col in new_cols:
        new_snippets.append(
            generate_dimension_snippet(
                col["name"],
                col.get("type", "STRING"),
                col.get("description"),
            )
        )
    inserted_text = "\n".join(new_snippets) + "\n"

    updated_content = (
        current_content[:last_brace_index]
        + inserted_text
        + current_content[last_brace_index:]
    )
    existing_file.write_text(updated_content, encoding="utf-8")
    return (True, str(existing_file), "appended_human_view")


def fetch_bq_table_schema(
    project: str,
    dataset: str,
    table: str,
) -> list[dict[str, Any]]:
    """Fetch BigQuery table schema using bq CLI or REST API."""
    # 1. Try bq CLI
    if shutil.which("bq"):
        cmd = [
            "bq",
            "show",
            "--format=json",
            f"{project}:{dataset}.{table}",
        ]
        try:
            res = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                check=False,
                timeout=30,
            )
            if res.returncode == 0 and res.stdout.strip():
                data = json.loads(res.stdout)
                fields = (
                    data.get("schema", {}).get("fields")
                    if isinstance(data, dict)
                    else None
                )
                if isinstance(fields, list):
                    return fields
        except Exception as e:  # noqa: BLE001
            logger.debug(f"bq show notice for {table}: {e}")

    # 2. Try REST API via requests with gcloud token
    try:
        import requests

        token = None
        if shutil.which("gcloud"):
            token_res = subprocess.run(
                ["gcloud", "auth", "print-access-token"],
                capture_output=True,
                text=True,
                check=False,
                timeout=10,
            )
            if token_res.returncode == 0:
                token = token_res.stdout.strip()

        if token:
            url = f"https://bigquery.googleapis.com/bigquery/v2/projects/{project}/datasets/{dataset}/tables/{table}"
            resp = requests.get(
                url,
                headers={"Authorization": f"Bearer {token}"},
                timeout=15,
            )
            if resp.status_code == 200:
                data = resp.json()
                fields = data.get("schema", {}).get("fields")
                if isinstance(fields, list):
                    return fields
    except Exception as e:  # noqa: BLE001
        logger.debug(f"REST API fetch notice for {table}: {e}")

    return []


def fetch_bq_tables(project: str, dataset: str) -> list[str]:
    """List tables in a BigQuery dataset using bq CLI or REST API."""
    if shutil.which("bq"):
        cmd = ["bq", "ls", "--format=json", f"{project}:{dataset}"]
        try:
            res = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                check=False,
                timeout=30,
            )
            if res.returncode == 0 and res.stdout.strip():
                entries = json.loads(res.stdout)
                if isinstance(entries, list):
                    tables = []
                    for entry in entries:
                        ref = entry.get("tableReference", {})
                        t_id = ref.get("tableId") or entry.get("id")
                        if t_id:
                            tables.append(t_id.split(".")[-1])
                    return tables
        except Exception as e:  # noqa: BLE001
            logger.debug(f"bq ls notice: {e}")
    return []


def log_sync_artifact(
    lookml_dir: str | Path,
    event: dict[str, Any],
    sdk: Any = None,
) -> None:
    """Log structured synchronization artifact locally and to Looker Artifact storage if available."""
    # Local log file
    log_file = Path(lookml_dir) / ".lkr_bq_sync_log.json"
    existing_events: list[dict[str, Any]] = []
    if log_file.is_file():
        try:
            existing_events = json.loads(log_file.read_text(encoding="utf-8"))
            if not isinstance(existing_events, list):
                existing_events = []
        except Exception:  # noqa: BLE001
            existing_events = []

    existing_events.append(event)
    log_file.write_text(json.dumps(existing_events, indent=2), encoding="utf-8")

    # Looker Artifact storage (if SDK is connected)
    if sdk and hasattr(sdk, "update_artifacts"):
        try:
            sdk.update_artifacts(
                namespace="lkr_bq_view_sync",
                body=[event],
            )
        except Exception as e:  # noqa: BLE001
            logger.debug(f"Notice updating Looker artifacts: {e}")


def create_git_pr(
    lookml_dir: str | Path,
    changed_files: list[str],
    project: str,
    dataset: str,
    branch_name: str | None = None,
) -> str | None:
    """Commit view changes and create a GitHub PR via gh CLI or local git branch."""
    lookml_path = Path(lookml_dir).resolve()
    ts = int(time.time())
    branch = branch_name or f"bq-sync/{dataset}-{ts}"

    # Verify lookml_dir is inside a git repo
    git_root_res = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        cwd=lookml_path,
        capture_output=True,
        text=True,
        check=False,
    )
    if git_root_res.returncode != 0:
        logger.warning(
            f"Directory {lookml_path} is not in a git repository. Skipping PR."
        )
        return None

    try:
        # Create and checkout branch
        subprocess.run(
            ["git", "checkout", "-b", branch],
            cwd=lookml_path,
            check=True,
            capture_output=True,
            text=True,
        )

        # Stage changed files
        for f in changed_files:
            subprocess.run(
                ["git", "add", f],
                cwd=lookml_path,
                check=True,
                capture_output=True,
                text=True,
            )

        # Commit
        file_list = "\n".join(f"- {Path(f).name}" for f in changed_files)
        commit_msg = (
            f"chore(lookml): auto-upsert views for {project}.{dataset}\n\n"
            f"Sync BigQuery table schema changes to LookML views.\n\n"
            f"Updated files:\n{file_list}"
        )
        subprocess.run(
            ["git", "commit", "-m", commit_msg],
            cwd=lookml_path,
            check=True,
            capture_output=True,
            text=True,
        )
        logger.info(f"Committed changes to branch '{branch}'.")

        # Push branch if remote exists
        remotes_res = subprocess.run(
            ["git", "remote"],
            cwd=lookml_path,
            capture_output=True,
            text=True,
            check=False,
        )
        has_remotes = bool(remotes_res.stdout.strip())
        if has_remotes:
            push_res = subprocess.run(
                ["git", "push", "-u", "origin", branch],
                cwd=lookml_path,
                capture_output=True,
                text=True,
                check=False,
            )
            if push_res.returncode != 0:
                logger.warning(f"Git push notice: {push_res.stderr.strip()}")

        # Attempt PR creation via gh CLI
        if shutil.which("gh") and has_remotes:
            body_text = (
                f"Automated LookML view update from BigQuery table changes in `{project}.{dataset}`.\n\n"
                f"Updated files:\n{file_list}"
            )
            pr_cmd = [
                "gh",
                "pr",
                "create",
                "--title",
                f"chore(lookml): auto-upsert views for {project}.{dataset}",
                "--body",
                body_text,
                "--head",
                branch,
            ]

            pr_res = subprocess.run(
                pr_cmd,
                cwd=lookml_path,
                capture_output=True,
                text=True,
                check=False,
            )
            if pr_res.returncode == 0:
                pr_url = pr_res.stdout.strip()
                logger.info(f"GitHub PR created successfully: {pr_url}")
                return pr_url
            logger.warning(
                f"gh pr create notice: {pr_res.stderr.strip()}. Changes remain on branch '{branch}'."
            )
    except Exception as e:  # noqa: BLE001
        logger.warning(f"Git / PR operation notice: {e}")

    return f"branch:{branch}"


def run_bq_change_sync(
    project: str,
    dataset: str,
    path: str,
    table: str | None = None,
    schema_file: str | None = None,
    create_pr: bool = False,
    branch_name: str | None = None,
    sdk: Any = None,
) -> dict[str, Any]:
    """Execute a single synchronization pass across BigQuery tables in a dataset."""
    lookml_dir = Path(path).resolve()
    if not lookml_dir.exists():
        lookml_dir.mkdir(parents=True, exist_ok=True)

    # 1. Resolve table schemas
    table_schemas: dict[str, list[dict[str, Any]]] = {}
    if schema_file and Path(schema_file).is_file():
        with open(schema_file, encoding="utf-8") as f:
            raw_data = json.load(f)
            if isinstance(raw_data, dict):
                if "tables" in raw_data and isinstance(raw_data["tables"], dict):
                    for t_name, t_info in raw_data["tables"].items():
                        cols = t_info.get("columns") or t_info.get("fields") or []
                        table_schemas[t_name] = cols
                elif "schema" in raw_data and "fields" in raw_data["schema"]:
                    # Single table schema file
                    t_name = table or Path(schema_file).stem
                    table_schemas[t_name] = raw_data["schema"]["fields"]
                else:
                    # Map of table_name -> list of columns
                    for t_name, cols in raw_data.items():
                        if isinstance(cols, list):
                            table_schemas[t_name] = cols
    elif table:
        cols = fetch_bq_table_schema(project, dataset, table)
        if cols:
            table_schemas[table] = cols
    else:
        tables = fetch_bq_tables(project, dataset)
        for t in tables:
            cols = fetch_bq_table_schema(project, dataset, t)
            if cols:
                table_schemas[t] = cols

    if not table_schemas:
        logger.info(f"No BigQuery tables found for {project}.{dataset}.")
        return {
            "status": "no_tables_found",
            "changed_files": [],
            "pr_url": None,
        }

    changed_files: list[str] = []
    actions: dict[str, str] = {}

    for t_name, cols in table_schemas.items():
        changed, file_path, action = upsert_view_file(
            lookml_dir=lookml_dir,
            project=project,
            dataset=dataset,
            table_name=t_name,
            columns=cols,
        )
        actions[t_name] = action
        if changed:
            changed_files.append(file_path)
            logger.info(f"LookML view {action}: {file_path}")

    pr_url = None
    if changed_files and create_pr:
        pr_url = create_git_pr(
            lookml_dir=lookml_dir,
            changed_files=changed_files,
            project=project,
            dataset=dataset,
            branch_name=branch_name,
        )

    # 3. Artifact logging
    timestamp_str = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    sync_event = {
        "event_id": f"{timestamp_str}_{project}.{dataset}",
        "timestamp": timestamp_str,
        "project": project,
        "dataset": dataset,
        "tables_checked": list(table_schemas.keys()),
        "changed_files": changed_files,
        "actions": actions,
        "status": "pr_opened"
        if pr_url and pr_url.startswith("http")
        else ("views_updated" if changed_files else "up_to_date"),
        "pr_url": pr_url,
    }
    log_sync_artifact(lookml_dir, sync_event, sdk=sdk)

    return {
        "status": sync_event["status"],
        "changed_files": changed_files,
        "actions": actions,
        "pr_url": pr_url,
    }
